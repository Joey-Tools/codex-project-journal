def _cleanup_git_snapshot_owner(
    owner: tempfile.TemporaryDirectory[str],
    operation: str,
    active_error: BaseException | None,
) -> bool:
    locator = pathlib.Path(owner.name)
    try:
        owner.cleanup()
    except BaseException as cleanup_error:
        details = _exception_details(
            cleanup_error,
            f"{_GIT_SNAPSHOT_CLEANUP_NOTE_PREFIX} after {operation}; "
            f"retained locator {locator}",
        )
        if active_error is not None:
            _add_exception_details(active_error, details)
            return False
        if isinstance(cleanup_error, Exception):
            failure = UnsupportedGitVersion(
                _bounded_signal_report_detail(details[0]),
            )
            _add_exception_details(failure, details[1:])
            raise failure from cleanup_error
        _add_exception_detail(cleanup_error, details[0])
        raise
    return True


def _cleanup_git_runtime_at_terminal() -> str | None:
    global _GIT_RUNTIME
    global _GIT_RUNTIME_ERROR

    runtime = _GIT_RUNTIME
    if runtime is None:
        _GIT_RUNTIME_ERROR = None
        return None
    locator = pathlib.Path(runtime.snapshot_owner.name)
    try:
        runtime.snapshot_owner.cleanup()
    except BaseException as exc:
        issue = _bounded_signal_report_detail(
            "Git runtime snapshot cleanup-incomplete; retained locator "
            f"{locator}: {exc}",
        )
        _GIT_RUNTIME_ERROR = UnsupportedGitVersion(issue)
        if not isinstance(exc, Exception):
            _add_exception_detail(exc, issue)
            raise
        return issue
    _GIT_RUNTIME = None
    _GIT_RUNTIME_ERROR = None
    return None


