def _fixed_git_executable() -> pathlib.Path:
    global _GIT_RUNTIME_ERROR

    if _GIT_RUNTIME_ERROR is not None:
        raise _GIT_RUNTIME_ERROR
    if _GIT_RUNTIME is None:
        raise UnsupportedGitVersion("Git runtime validation did not complete")
    try:
        _verify_git_runtime_snapshot(_GIT_RUNTIME)
    except UnsupportedGitVersion as exc:
        _GIT_RUNTIME_ERROR = exc
        raise
    return _GIT_RUNTIME.executable


def _git_command(repo: pathlib.Path, *args: str) -> list[str]:
    return [
        str(_fixed_git_executable()),
        "--no-pager",
        "--no-optional-locks",
        *SAFE_GIT_CONFIG_ARGS,
        "-C",
        str(repo),
        *args,
    ]


def _run_git(repo: pathlib.Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        _git_command(repo, *args),
        check=False,
        env=_git_environment(),
        stdin=subprocess.DEVNULL,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )


def _resolve_repo(repo_arg: str) -> pathlib.Path:
    candidate = pathlib.Path(repo_arg).expanduser().resolve()
    result = _run_git(candidate, "rev-parse", "--show-toplevel")
    if result.returncode != 0:
        detail = (
            result.stderr.strip() or result.stdout.strip() or "not a git repository"
        )
        raise UserError(f"{candidate} is not a git repository: {detail}")
    return pathlib.Path(result.stdout.strip()).resolve()


def _git_path(repo: pathlib.Path, rel: str) -> pathlib.Path:
    result = _run_git(repo, "rev-parse", "--git-path", rel)
    if result.returncode != 0:
        detail = (
            result.stderr.strip() or result.stdout.strip() or "git path lookup failed"
        )
        raise UserError(f"failed to resolve git path {rel!r}: {detail}")
    path = pathlib.Path(result.stdout.strip())
    if not path.is_absolute():
        path = repo / path
    return path


def _to_repo_rel(repo: pathlib.Path, path_arg: str) -> str:
    path = pathlib.Path(path_arg)
    if path.is_absolute():
        resolved = path.resolve()
    else:
        resolved = (repo / path).resolve()
    try:
        rel = resolved.relative_to(repo)
    except ValueError as exc:
        raise UserError(
            f"output path must resolve inside the repository: {resolved}"
        ) from exc
    return rel.as_posix()


def _strip_quotes(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
        return value[1:-1]
    return value


def _check_deadline(deadline: float | None, error: str) -> None:
    if deadline is not None and time.monotonic() >= deadline:
        raise UserError(error)


def _validate_frontmatter_value(
    value: str,
    *,
    label: str,
    field: str,
    list_item: bool = False,
) -> str:
    limit = (
        MAX_FRONTMATTER_LIST_ITEM_CHARS if list_item else MAX_FRONTMATTER_VALUE_CHARS
    )
    if len(value) > limit:
        kind = "list item" if list_item else "value"
        raise JournalLimitExceeded(
            f"{label}: field {field!r} {kind} exceeds {limit} characters"
        )
    return value


def _parse_scalar(
    value: str,
    *,
    label: str,
    field: str,
    deadline: float | None = None,
    deadline_error: str = "journal validation exceeded its shared deadline",
) -> Any:
    _check_deadline(deadline, deadline_error)
    value = value.strip()
    _validate_frontmatter_value(value, label=label, field=field)
    if value == "[]":
        return []
    if value.startswith("[") and value.endswith("]"):
        inner = value[1:-1].strip()
        if not inner:
            return []
        raw_parts = inner.split(",", MAX_FRONTMATTER_LIST_ITEMS)
        if len(raw_parts) > MAX_FRONTMATTER_LIST_ITEMS:
            raise JournalLimitExceeded(
                f"{label}: field {field!r} exceeds "
                f"{MAX_FRONTMATTER_LIST_ITEMS} list items"
            )
        items: list[str] = []
        for raw_part in raw_parts:
            _check_deadline(deadline, deadline_error)
            part = _strip_quotes(raw_part.strip())
            if not part:
                continue
            items.append(
                _validate_frontmatter_value(
                    part,
                    label=label,
                    field=field,
                    list_item=True,
                )
            )
        return items
    return _strip_quotes(value)


def _parse_frontmatter_text(
    text: str,
    label: str,
    *,
    deadline: float | None = None,
    deadline_error: str = "journal validation exceeded its shared deadline",
) -> dict[str, Any]:
    _check_deadline(deadline, deadline_error)
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        raise UserError(f"{label}: missing frontmatter")

    end = None
    for index, line in enumerate(lines[1:], start=1):
        _check_deadline(deadline, deadline_error)
        if index + 1 > MAX_FRONTMATTER_LINES:
            raise JournalLimitExceeded(
                f"{label}: frontmatter exceeds {MAX_FRONTMATTER_LINES} lines"
            )
        if line.strip() == "---":
            end = index
            break
    if end is None:
        raise UserError(f"{label}: unterminated frontmatter")

    fields: dict[str, Any] = {}
    current_key: str | None = None
    field_count = 0
    for raw_line in lines[1:end]:
        _check_deadline(deadline, deadline_error)
        if not raw_line.strip():
            continue
        if raw_line.startswith((" ", "\t")):
            if current_key is None:
                continue
            stripped = raw_line.strip()
            if stripped.startswith("- "):
                existing = fields.get(current_key)
                if not isinstance(existing, list):
                    existing = []
                    fields[current_key] = existing
                if len(existing) >= MAX_FRONTMATTER_LIST_ITEMS:
                    raise JournalLimitExceeded(
                        f"{label}: field {current_key!r} exceeds "
                        f"{MAX_FRONTMATTER_LIST_ITEMS} list items"
                    )
                item = _strip_quotes(stripped[2:].strip())
                if item:
                    existing.append(
                        _validate_frontmatter_value(
                            item,
                            label=label,
                            field=current_key,
                            list_item=True,
                        )
                    )
            continue
        if ":" not in raw_line:
            raise UserError(f"{label}: invalid frontmatter line: {raw_line}")
        key, raw_value = raw_line.split(":", 1)
        key = key.strip()
        if not key:
            raise UserError(f"{label}: empty frontmatter key")
        field_count += 1
        if field_count > MAX_FRONTMATTER_FIELDS:
            raise JournalLimitExceeded(
                f"{label}: frontmatter exceeds {MAX_FRONTMATTER_FIELDS} fields"
            )
        fields[key] = _parse_scalar(
            raw_value,
            label=label,
            field=key,
            deadline=deadline,
            deadline_error=deadline_error,
        )
        current_key = key
    return fields


def _parse_frontmatter(path: pathlib.Path) -> dict[str, Any]:
    content = path.read_bytes()
    if len(content) > MAX_TRACKED_JOURNAL_BLOB_BYTES:
        raise JournalLimitExceeded(
            f"{path}: journal file exceeds {MAX_TRACKED_JOURNAL_BLOB_BYTES} bytes"
        )
    try:
        text = content.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise UserError(f"{path}: journal file is not valid UTF-8") from exc
    return _parse_frontmatter_text(text, str(path))


def _as_list(
    value: Any,
    *,
    label: str,
    field: str,
    deadline: float | None = None,
    deadline_error: str = "journal validation exceeded its shared deadline",
) -> list[str]:
    _check_deadline(deadline, deadline_error)
    if value is None or value == "":
        return []
    if isinstance(value, list):
        if len(value) > MAX_FRONTMATTER_LIST_ITEMS:
            raise JournalLimitExceeded(
                f"{label}: field {field!r} exceeds "
                f"{MAX_FRONTMATTER_LIST_ITEMS} list items"
            )
        items: list[str] = []
        for item in value:
            _check_deadline(deadline, deadline_error)
            text = str(item).strip()
            if not text:
                continue
            items.append(
                _validate_frontmatter_value(
                    text,
                    label=label,
                    field=field,
                    list_item=True,
                )
            )
        return items
    text = str(value).strip()
    return (
        [
            _validate_frontmatter_value(
                text,
                label=label,
                field=field,
                list_item=True,
            )
        ]
        if text
        else []
    )


def _journal_paths(repo: pathlib.Path) -> list[pathlib.Path]:
    root = repo / JOURNAL_ROOT
    if not root.exists():
        return []
    paths: list[pathlib.Path] = []
    for path in root.rglob("*.md"):
        if _is_generated_index(path):
            continue
        paths.append(path)
        if len(paths) > MAX_JOURNAL_ENTRIES:
            raise JournalLimitExceeded(
                f"journal entry count exceeds {MAX_JOURNAL_ENTRIES}"
            )
    return sorted(paths)


def _parse_index_stage_record(
    record: bytes,
    records: dict[bytes, list[tuple[bytes, bytes, bytes]]],
) -> None:
    journal_prefix = JOURNAL_ROOT.as_posix().encode("ascii") + b"/"
    default_index = DEFAULT_INDEX.as_posix().encode("ascii")

    metadata, separator, raw_path = record.partition(b"\t")
    fields = metadata.split(b" ")
    if not separator or not raw_path or len(fields) != 3:
        raise UserError("malformed git ls-files stage record")
    mode, oid, stage = fields
    if not INDEX_MODE_RE.fullmatch(mode):
        raise UserError("malformed git ls-files mode")
    if not INDEX_OID_RE.fullmatch(oid):
        raise UserError("malformed git ls-files object id")
    if stage not in {b"0", b"1", b"2", b"3"}:
        raise UserError("malformed git ls-files stage")
    if not raw_path.startswith(journal_prefix):
        raise UserError("git ls-files returned a path outside the journal root")
    path_parts = raw_path.split(b"/")
    if any(part in {b"", b".", b".."} for part in path_parts):
        raise UserError("git ls-files returned an unsafe journal path")
    if raw_path == default_index or not raw_path.endswith(b".md"):
        return
    records.setdefault(raw_path, []).append((mode, oid, stage))


def _index_journal_blobs_from_records(
    records: dict[bytes, list[tuple[bytes, bytes, bytes]]],
) -> list[IndexJournalBlob]:
    blobs: list[IndexJournalBlob] = []
    for raw_path, path_records in sorted(records.items()):
        if len(path_records) != 1:
            continue
        mode, oid, stage = path_records[0]
        if stage != b"0" or mode not in REGULAR_INDEX_MODES:
            continue
        blobs.append(
            IndexJournalBlob(
                mode=mode,
                oid=oid.decode("ascii"),
                raw_path=raw_path,
                rel_path=os.fsdecode(raw_path),
            )
        )
    return blobs


class _IndexStageStreamParser:
    def __init__(self, *, max_records: int = MAX_TRACKED_JOURNAL_RECORDS) -> None:
        self._max_records = max_records
        self._pending = bytearray()
        self._record_count = 0
        self._records: dict[bytes, list[tuple[bytes, bytes, bytes]]] = {}
        self._blobs: list[IndexJournalBlob] | None = None

    def feed(self, chunk: bytes) -> None:
        if self._blobs is not None:
            raise RuntimeError("cannot feed a finished Git index parser")
        self._pending.extend(chunk)
        consumed = 0
        while True:
            terminator = self._pending.find(0, consumed)
            if terminator < 0:
                break
            record = bytes(self._pending[consumed:terminator])
            consumed = terminator + 1
            if not record:
                continue
            self._record_count += 1
            if self._record_count > self._max_records:
                raise UserError(
                    f"tracked journal index exceeds {self._max_records} records"
                )
            _parse_index_stage_record(record, self._records)
        if consumed:
            del self._pending[:consumed]

    def finish(self) -> None:
        if self._blobs is not None:
            return
        if self._pending:
            raise UserError("malformed git ls-files output: missing NUL terminator")
        self._blobs = _index_journal_blobs_from_records(self._records)

    def blobs(self) -> list[IndexJournalBlob]:
        if self._blobs is None:
            raise RuntimeError("Git index parser has not reached EOF")
        return self._blobs


def _parse_index_journal_blobs(output: bytes) -> list[IndexJournalBlob]:
    if len(output) > MAX_TRACKED_JOURNAL_INDEX_BYTES:
        raise UserError(
            "tracked journal index output exceeds "
            f"{MAX_TRACKED_JOURNAL_INDEX_BYTES} bytes"
        )
    parser = _IndexStageStreamParser()
    parser.feed(output)
    parser.finish()
    return parser.blobs()


class _CatFileBatchStreamParser:
    def __init__(
        self,
        blobs: list[IndexJournalBlob],
        *,
        max_records: int = MAX_TRACKED_JOURNAL_RECORDS,
        max_blob_bytes: int = MAX_TRACKED_JOURNAL_BLOB_BYTES,
        max_total_bytes: int = MAX_TRACKED_JOURNAL_TOTAL_BYTES,
        max_header_bytes: int = MAX_CAT_FILE_BATCH_HEADER_BYTES,
    ) -> None:
        if min(max_records, max_blob_bytes, max_total_bytes, max_header_bytes) < 0:
            raise ValueError("cat-file batch limits must not be negative")
        if len(blobs) > max_records:
            raise UserError(f"tracked journal blob batch exceeds {max_records} records")

        requested_oids: list[bytes] = []
        for blob in blobs:
            try:
                raw_oid = blob.oid.encode("ascii")
            except UnicodeEncodeError as exc:
                raise UserError(
                    f"{blob.rel_path}: invalid requested index blob object id"
                ) from exc
            if not INDEX_OID_RE.fullmatch(raw_oid):
                raise UserError(
                    f"{blob.rel_path}: invalid requested index blob object id"
                )
            requested_oids.append(raw_oid)

        self._blobs = tuple(blobs)
        self._requested_oids = tuple(requested_oids)
        self._max_blob_bytes = max_blob_bytes
        self._max_total_bytes = max_total_bytes
        self._max_header_bytes = max_header_bytes
        self._pending = bytearray()
        self._contents: list[bytes] = []
        self._expected_size: int | None = None
        self._total_bytes = 0
        self._finished = False

    def _parse_header(self, header: bytes) -> None:
        blob = self._blobs[len(self._contents)]
        expected_oid = self._requested_oids[len(self._contents)]
        fields = header.split(b" ")
        if len(fields) not in {2, 3} or any(not field for field in fields):
            raise UserError(f"{blob.rel_path}: malformed git cat-file batch header")
        if fields[0] != expected_oid:
            raise UserError(
                f"{blob.rel_path}: git cat-file batch returned a mismatched object id"
            )
        if len(fields) == 2:
            if fields[1] == b"missing":
                raise UserError(f"{blob.rel_path}: index blob is missing")
            raise UserError(f"{blob.rel_path}: malformed git cat-file batch header")

        _raw_oid, object_type, raw_size = fields
        if object_type != b"blob":
            raise UserError(
                f"{blob.rel_path}: git cat-file batch returned "
                f"object type {object_type.decode('ascii', errors='replace')!r}, "
                "expected 'blob'"
            )
        if not raw_size.isdigit():
            raise UserError(f"{blob.rel_path}: invalid git cat-file batch object size")
        size = int(raw_size)
        if size > self._max_blob_bytes:
            raise UserError(
                f"{blob.rel_path}: index blob exceeds {self._max_blob_bytes} bytes"
            )
        if self._total_bytes + size > self._max_total_bytes:
            raise UserError(
                f"tracked journal blobs exceed {self._max_total_bytes} total bytes"
            )
        self._total_bytes += size
        self._expected_size = size

    def feed(self, chunk: bytes) -> None:
        if self._finished:
            raise RuntimeError("cannot feed a finished Git cat-file batch parser")
        self._pending.extend(chunk)
        while True:
            if len(self._contents) == len(self._blobs):
                if self._pending:
                    raise UserError(
                        "git cat-file batch returned unexpected extra response data"
                    )
                return

            if self._expected_size is None:
                terminator = self._pending.find(b"\n")
                if terminator < 0:
                    if len(self._pending) > self._max_header_bytes:
                        blob = self._blobs[len(self._contents)]
                        raise UserError(
                            f"{blob.rel_path}: git cat-file batch header exceeds "
                            f"{self._max_header_bytes} bytes"
                        )
                    return
                if terminator > self._max_header_bytes:
                    blob = self._blobs[len(self._contents)]
                    raise UserError(
                        f"{blob.rel_path}: git cat-file batch header exceeds "
                        f"{self._max_header_bytes} bytes"
                    )
                header = bytes(self._pending[:terminator])
                del self._pending[: terminator + 1]
                self._parse_header(header)

            assert self._expected_size is not None
            framed_size = self._expected_size + 1
            if len(self._pending) < framed_size:
                return
            if self._pending[self._expected_size : framed_size] != b"\n":
                blob = self._blobs[len(self._contents)]
                raise UserError(
                    f"{blob.rel_path}: malformed git cat-file batch content framing"
                )
            self._contents.append(bytes(self._pending[: self._expected_size]))
            del self._pending[:framed_size]
            self._expected_size = None

    def finish(self) -> None:
        if self._finished:
            return
        if self._expected_size is not None:
            blob = self._blobs[len(self._contents)]
            raise UserError(f"{blob.rel_path}: truncated git cat-file batch content")
        if self._pending:
            blob = self._blobs[len(self._contents)]
            raise UserError(f"{blob.rel_path}: truncated git cat-file batch header")
        if len(self._contents) != len(self._blobs):
            raise UserError("git cat-file batch returned fewer records than requested")
        self._finished = True

    def contents(self) -> list[bytes]:
        if not self._finished:
            raise RuntimeError("Git cat-file batch parser has not reached EOF")
        return list(self._contents)

    def request_data(self) -> bytes:
        return b"".join(oid + b"\n" for oid in self._requested_oids)


def _close_selector_stream(
    selector: selectors.BaseSelector,
    stream: Any,
) -> None:
    try:
        selector.unregister(stream)
    except (KeyError, ValueError):
        pass
    try:
        stream.close()
    except OSError:
        pass


def _discard_selector_output(
    selector: selectors.BaseSelector,
    deadline: float,
) -> None:
    while selector.get_map():
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            return
        try:
            events = selector.select(remaining)
        except OSError:
            return
        if not events:
            continue
        for key, _mask in events:
            if key.data == "stdin":
                _close_selector_stream(selector, key.fileobj)
                continue
            try:
                chunk = os.read(key.fd, PROCESS_READ_CHUNK_BYTES)
            except BlockingIOError:
                continue
            except OSError:
                chunk = b""
            if not chunk:
                _close_selector_stream(selector, key.fileobj)


def _close_selector(selector: selectors.BaseSelector) -> None:
    try:
        mapping = selector.get_map()
    except (OSError, ValueError):
        mapping = None
    if mapping is not None:
        for key in list(mapping.values()):
            _close_selector_stream(selector, key.fileobj)
    try:
        selector.close()
    except OSError:
        pass


def _signal_process_group(
    process: subprocess.Popen[bytes],
    sig: int,
) -> _ProcessSignalResult:
    try:
        if os.name == "posix":
            os.killpg(process.pid, sig)
        elif sig == signal.SIGTERM:
            process.terminate()
        else:
            process.kill()
    except ProcessLookupError:
        return _ProcessSignalResult(target_existed=False)
    except OSError as exc:
        return _ProcessSignalResult(target_existed=True, error=str(exc))
    return _ProcessSignalResult(target_existed=True)


def _bound_process_group_exists(
    process: subprocess.Popen[bytes],
) -> tuple[bool, str | None]:
    if os.name != "posix":
        raise RuntimeError("process-group probes require POSIX")
    try:
        os.killpg(process.pid, 0)
    except ProcessLookupError:
        return False, None
    except PermissionError:
        # Darwin can report EPERM for the already-exited, WNOWAIT-fenced
        # leader after the last live member leaves the group. Every live
        # process in a group created by this helper retains the caller's
        # credentials, so a live member remains signal-probeable.
        return False, None
    except OSError as exc:
        return True, str(exc)
    return True, None


def _wait_for_bound_process_group_absence(
    process: subprocess.Popen[bytes],
    deadline: float,
) -> tuple[bool, str | None]:
    while True:
        exists, error = _bound_process_group_exists(process)
        if error is not None or not exists:
            return exists, error
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            return True, None
        time.sleep(min(0.01, remaining))


def _waitid_returncode(result: Any) -> int:
    if result.si_code == os.CLD_EXITED:
        return int(result.si_status)
    if result.si_code in {os.CLD_KILLED, os.CLD_DUMPED}:
        return -int(result.si_status)
    raise UserError(f"unexpected POSIX child status code {result.si_code!r}")


def _wait_for_process_status_without_reaping(
    process: subprocess.Popen[bytes],
    deadline: float,
    timeout_error: str,
) -> int:
    if not all(
        hasattr(os, name)
        for name in ("waitid", "WNOWAIT", "WEXITED", "WNOHANG", "P_PID")
    ):
        raise UserError("POSIX WNOWAIT status observation is unavailable")
    options = os.WEXITED | os.WNOHANG | os.WNOWAIT
    while True:
        try:
            result = os.waitid(os.P_PID, process.pid, options)
        except ChildProcessError as exc:
            raise _ProcessIdentityLost(
                "direct child identity was lost before final process-group cleanup"
            ) from exc
        except InterruptedError:
            result = None
        except OSError as exc:
            raise UserError(
                f"failed to observe direct child without reaping: {exc}"
            ) from exc
        if result is not None:
            if int(result.si_pid) != process.pid:
                raise _ProcessIdentityLost(
                    "POSIX status observation returned a mismatched child"
                )
            return _waitid_returncode(result)
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            raise UserError(timeout_error)
        time.sleep(min(0.01, remaining))


def _reap_after_final_group_signal(
    process: subprocess.Popen[bytes],
    expected_returncode: int | None,
    deadline: float,
) -> str | None:
    try:
        returncode = process.wait(timeout=max(0.0, deadline - time.monotonic()))
    except subprocess.TimeoutExpired:
        return "direct child did not exit before the cleanup deadline"
    except OSError as exc:
        return f"failed to reap direct child: {exc}"
    if expected_returncode is not None and returncode != expected_returncode:
        return (
            "reaped direct-child status changed from "
            f"{expected_returncode} to {returncode}"
        )
    return None


def _annotate_cleanup_interruption(
    exc: BaseException,
    operation: str,
    phase: str,
) -> None:
    detail = f"{operation} cleanup-incomplete: {phase} was interrupted"
    add_note = getattr(exc, "add_note", None)
    if callable(add_note):
        add_note(detail)
        return
    existing = str(exc).strip()
    exc.args = (f"{existing}; {detail}" if existing else detail,)


def _terminate_process_group_and_reap(
    process: subprocess.Popen[bytes],
    selector: selectors.BaseSelector,
    ownership: _ProcessOwnership | None = None,
) -> str | None:
    """Clean up while the unreaped direct child still fences its PID/PGID."""
    if ownership is None:
        ownership = _ProcessOwnership.for_process()
        ownership.claim_group_cleanup()
    elif ownership.state != "cleanup-claimed":
        raise RuntimeError(
            f"cleanup requires claimed ownership, got {ownership.state!r}"
        )

    issues: list[str] = []
    observed_returncode: int | None = None
    kill_deadline = time.monotonic() + GIT_PROCESS_KILL_DRAIN_SECONDS

    if isinstance(process.returncode, int):
        observed_returncode = process.returncode
    elif os.name == "posix":
        group_exists, probe_error = _bound_process_group_exists(process)
        if probe_error is not None:
            issues.append(f"failed to probe bound process group: {probe_error}")
        if group_exists:
            term_result = _signal_process_group(process, signal.SIGTERM)
            if term_result.error is not None:
                issues.append(
                    f"failed to signal bound process group with SIGTERM: "
                    f"{term_result.error}"
                )
        else:
            term_result = _ProcessSignalResult(target_existed=False)
        terminate_deadline = time.monotonic() + GIT_PROCESS_TERMINATE_GRACE_SECONDS
        _discard_selector_output(selector, terminate_deadline)
        group_exists = term_result.target_existed
        probe_error = None
        if group_exists:
            group_exists, probe_error = _wait_for_bound_process_group_absence(
                process,
                terminate_deadline,
            )
        if probe_error is not None:
            issues.append(f"failed to probe bound process group: {probe_error}")
        if group_exists:
            kill_signal = getattr(signal, "SIGKILL", signal.SIGTERM)
            kill_result = _signal_process_group(process, kill_signal)
            if kill_result.error is not None:
                issues.append(
                    f"failed to signal bound process group with SIGKILL: "
                    f"{kill_result.error}"
                )
        kill_deadline = time.monotonic() + GIT_PROCESS_KILL_DRAIN_SECONDS
        _discard_selector_output(selector, kill_deadline)
        try:
            observed_returncode = _wait_for_process_status_without_reaping(
                process,
                kill_deadline,
                "direct child did not exit after final process-group signal",
            )
        except _ProcessIdentityLost as exc:
            issues.append(str(exc))
        except UserError as exc:
            issues.append(str(exc))
    else:
        term_result = _signal_process_group(process, signal.SIGTERM)
        if term_result.error is not None:
            issues.append(f"failed to terminate direct child: {term_result.error}")
        terminate_deadline = time.monotonic() + GIT_PROCESS_TERMINATE_GRACE_SECONDS
        _discard_selector_output(selector, terminate_deadline)
        try:
            observed_returncode = process.wait(
                timeout=max(0.0, terminate_deadline - time.monotonic())
            )
        except subprocess.TimeoutExpired:
            kill_signal = getattr(signal, "SIGKILL", signal.SIGTERM)
            kill_result = _signal_process_group(process, kill_signal)
            if kill_result.error is not None:
                issues.append(f"failed to kill direct child: {kill_result.error}")
            kill_deadline = time.monotonic() + GIT_PROCESS_KILL_DRAIN_SECONDS
            _discard_selector_output(selector, kill_deadline)
        except OSError as exc:
            issues.append(f"failed to reap direct child: {exc}")
            kill_deadline = terminate_deadline
        else:
            kill_deadline = terminate_deadline

    _close_selector(selector)
    ownership.transfer_to_reap(observed_returncode)
    reap_error = _reap_after_final_group_signal(
        process,
        observed_returncode,
        kill_deadline,
    )
    if reap_error is not None:
        issues.append(reap_error)
    else:
        ownership.release()
    return "; ".join(issues) or None


def _capture_bounded_process(
    argv: list[str],
    *,
    env: dict[str, str],
    stdin_data: bytes | None = None,
    timeout_seconds: float,
    stdout_limit: int,
    stderr_limit: int,
    stdout_feed: Callable[[bytes], None] | None = None,
    stdout_finish: Callable[[], None] | None = None,
    stdout_overflow_error: str,
    stderr_overflow_error: str,
    timeout_error: str,
    operation: str = "Git index snapshot",
    deadline: float | None = None,
) -> subprocess.CompletedProcess[bytes]:
    if timeout_seconds <= 0:
        raise ValueError("timeout_seconds must be positive")
    if stdout_limit < 0 or stderr_limit < 0:
        raise ValueError("stream limits must not be negative")

    started_at = time.monotonic()
    operation_deadline = started_at + timeout_seconds
    if deadline is not None:
        operation_deadline = min(operation_deadline, deadline)
    if operation_deadline <= started_at:
        raise UserError(timeout_error)
    try:
        selector = selectors.DefaultSelector()
    except OSError as exc:
        raise UserError(f"failed to create {operation} selector: {exc}") from exc
    stdout = bytearray()
    stderr = bytearray()
    stdin_offset = 0
    try:
        process = subprocess.Popen(
            argv,
            env=env,
            stdin=subprocess.PIPE if stdin_data is not None else subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            start_new_session=os.name == "posix",
        )
    except OSError as exc:
        _close_selector(selector)
        raise UserError(f"failed to start {operation}: {exc}") from exc

    ownership = _ProcessOwnership.for_process()
    selector_open = True
    try:
        assert process.stdout is not None
        assert process.stderr is not None
        for stream, stream_name in (
            (process.stdout, "stdout"),
            (process.stderr, "stderr"),
        ):
            try:
                os.set_blocking(stream.fileno(), False)
                selector.register(
                    stream,
                    selectors.EVENT_READ,
                    data=stream_name,
                )
            except OSError as exc:
                raise UserError(
                    f"failed to configure {operation} {stream_name}: {exc}"
                ) from exc

        if stdin_data is not None:
            assert process.stdin is not None
            try:
                if stdin_data:
                    os.set_blocking(process.stdin.fileno(), False)
                    selector.register(
                        process.stdin,
                        selectors.EVENT_WRITE,
                        data="stdin",
                    )
                else:
                    process.stdin.close()
            except OSError as exc:
                raise UserError(
                    f"failed to configure {operation} stdin: {exc}"
                ) from exc

        while selector.get_map():
            remaining = operation_deadline - time.monotonic()
            if remaining <= 0:
                raise UserError(timeout_error)
            try:
                events = selector.select(remaining)
            except OSError as exc:
                raise UserError(
                    f"failed to monitor {operation} streams: {exc}"
                ) from exc
            if not events:
                continue
            for key, _mask in events:
                if time.monotonic() >= operation_deadline:
                    raise UserError(timeout_error)
                if key.data == "stdin":
                    assert stdin_data is not None
                    try:
                        written = os.write(
                            key.fd,
                            stdin_data[
                                stdin_offset : stdin_offset + PROCESS_READ_CHUNK_BYTES
                            ],
                        )
                    except BlockingIOError:
                        continue
                    except OSError as exc:
                        raise UserError(
                            f"failed to write {operation} stdin: {exc}"
                        ) from exc
                    if written <= 0:
                        raise UserError(
                            f"failed to write {operation} stdin: short write"
                        )
                    stdin_offset += written
                    if stdin_offset == len(stdin_data):
                        _close_selector_stream(selector, key.fileobj)
                    continue
                target = stdout if key.data == "stdout" else stderr
                limit = stdout_limit if key.data == "stdout" else stderr_limit
                available = limit - len(target)
                read_size = min(PROCESS_READ_CHUNK_BYTES, available + 1)
                try:
                    chunk = os.read(key.fd, read_size)
                except BlockingIOError:
                    continue
                except OSError as exc:
                    raise UserError(
                        f"failed to read {operation} {key.data}: {exc}"
                    ) from exc
                if not chunk:
                    _close_selector_stream(selector, key.fileobj)
                    continue
                if len(chunk) > available:
                    if key.data == "stdout":
                        raise UserError(stdout_overflow_error)
                    raise UserError(stderr_overflow_error)
                if key.data == "stdout" and stdout_feed is not None:
                    stdout_feed(chunk)
                target.extend(chunk)

        if os.name == "posix":
            returncode = _wait_for_process_status_without_reaping(
                process,
                operation_deadline,
                timeout_error,
            )
            try:
                ownership.claim_group_cleanup()
                cleanup_error = _terminate_process_group_and_reap(
                    process,
                    selector,
                    ownership,
                )
            except BaseException as cleanup_exc:
                _close_selector(selector)
                selector_open = False
                if ownership.needs_reap:
                    _annotate_cleanup_interruption(
                        cleanup_exc,
                        operation,
                        "final direct-child reap",
                    )
                else:
                    ownership.abandon_incomplete()
                    _annotate_cleanup_interruption(
                        cleanup_exc,
                        operation,
                        "process-group cleanup",
                    )
                raise
            selector_open = False
            if cleanup_error is not None:
                ownership.abandon_incomplete()
                child_detail = stderr.decode(
                    "utf-8",
                    errors="replace",
                ).strip()
                detail_suffix = (
                    f"; bounded child stderr: {child_detail}" if child_detail else ""
                )
                raise UserError(
                    f"{operation} cleanup-incomplete after exit "
                    f"{returncode}: {cleanup_error}{detail_suffix}"
                )
            ownership.release()
            if returncode == 0 and stdout_finish is not None:
                stdout_finish()
        else:
            remaining = operation_deadline - time.monotonic()
            if remaining <= 0:
                raise UserError(timeout_error)
            try:
                returncode = process.wait(timeout=remaining)
            except subprocess.TimeoutExpired as exc:
                raise UserError(timeout_error) from exc
            ownership.transfer_to_reap(returncode)
            ownership.release()
            if returncode == 0 and stdout_finish is not None:
                stdout_finish()
            _close_selector(selector)
            selector_open = False
    except _ProcessIdentityLost as exc:
        ownership.release()
        if selector_open:
            _close_selector(selector)
            selector_open = False
        raise UserError(
            f"{exc}; {operation} cleanup-incomplete: process-group cleanup "
            "was skipped after leader identity loss"
        ) from exc
    except BaseException as exc:
        cleanup_error: str | None = None
        if ownership.permits_group_cleanup:
            try:
                ownership.claim_group_cleanup()
                cleanup_error = _terminate_process_group_and_reap(
                    process,
                    selector,
                )
            except BaseException as cleanup_exc:
                ownership.abandon_incomplete()
                _close_selector(selector)
                selector_open = False
                _annotate_cleanup_interruption(
                    cleanup_exc,
                    operation,
                    "process-group cleanup",
                )
                raise
            selector_open = False
            if cleanup_error is None:
                ownership.release()
        elif ownership.needs_reap:
            if selector_open:
                _close_selector(selector)
                selector_open = False
            try:
                cleanup_error = _reap_after_final_group_signal(
                    process,
                    ownership.expected_returncode,
                    time.monotonic() + GIT_PROCESS_KILL_DRAIN_SECONDS,
                )
            except BaseException:
                _annotate_cleanup_interruption(
                    exc,
                    operation,
                    "reap-only cleanup",
                )
                raise exc
            if cleanup_error is None:
                ownership.release()
        elif ownership.state == "cleanup-claimed":
            ownership.abandon_incomplete()
            if selector_open:
                _close_selector(selector)
                selector_open = False
            _annotate_cleanup_interruption(
                exc,
                operation,
                "cleanup ownership handoff",
            )
        elif selector_open:
            _close_selector(selector)
            selector_open = False
        if cleanup_error is not None:
            cleanup_message = f"{operation} cleanup-incomplete: {cleanup_error}"
            if isinstance(exc, UserError):
                raise UserError(f"{exc}; {cleanup_message}") from exc
            if isinstance(exc, Exception):
                raise UserError(f"{exc}; {cleanup_message}") from exc
            add_note = getattr(exc, "add_note", None)
            if add_note is not None:
                add_note(cleanup_message)
        raise

    return subprocess.CompletedProcess(
        argv,
        returncode,
        bytes(stdout),
        bytes(stderr),
    )


def _snapshot_git_executable(
    source: pathlib.Path,
) -> tuple[
    pathlib.Path,
    str,
    tuple[int, int, int, int, int],
    tuple[int, int, int, int],
    tempfile.TemporaryDirectory[str],
]:
    owner = tempfile.TemporaryDirectory(prefix="project-journal-git-runtime-")
    directory = pathlib.Path(owner.name).resolve()
    os.chmod(directory, 0o700)
    snapshot = directory / "git"
    source_flags = os.O_RDONLY | getattr(os, "O_CLOEXEC", 0)
    source_flags |= getattr(os, "O_NOFOLLOW", 0)
    destination_flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
    destination_flags |= getattr(os, "O_CLOEXEC", 0)
    destination_flags |= getattr(os, "O_NOFOLLOW", 0)
    try:
        source_fd = os.open(source, source_flags)
        try:
            source_before = os.fstat(source_fd)
            if not stat.S_ISREG(source_before.st_mode):
                raise OSError("selected Git executable is not a regular file")
            destination_fd = os.open(snapshot, destination_flags, 0o600)
            digest = hashlib.sha256()
            try:
                while True:
                    chunk = os.read(source_fd, PROCESS_READ_CHUNK_BYTES)
                    if not chunk:
                        break
                    digest.update(chunk)
                    offset = 0
                    while offset < len(chunk):
                        written = os.write(destination_fd, chunk[offset:])
                        if written <= 0:
                            raise OSError("short write while snapshotting Git")
                        offset += written
                os.fsync(destination_fd)
                os.fchmod(destination_fd, 0o500)
                destination_stat = os.fstat(destination_fd)
            finally:
                os.close(destination_fd)
            source_after = os.fstat(source_fd)
        finally:
            os.close(source_fd)

        source_signals = (
            "st_dev",
            "st_ino",
            "st_mode",
            "st_size",
            "st_mtime_ns",
            "st_ctime_ns",
        )
        if any(
            getattr(source_before, name) != getattr(source_after, name)
            for name in source_signals
        ):
            raise OSError("selected Git executable changed while being snapshotted")
        if destination_stat.st_size != source_after.st_size:
            raise OSError("Git runtime snapshot size does not match its source")
        directory_stat = os.stat(directory, follow_symlinks=False)
        return (
            snapshot,
            digest.hexdigest(),
            _file_identity(destination_stat),
            _directory_identity(directory_stat),
            owner,
        )
    except BaseException:
        owner.cleanup()
        raise


def _initialize_git_runtime() -> None:
    global _GIT_RUNTIME
    global _GIT_RUNTIME_ERROR

    if _GIT_RUNTIME is not None or _GIT_RUNTIME_ERROR is not None:
        return
    if os.name != "posix":
        _GIT_RUNTIME_ERROR = UnsupportedPlatform(
            "project_journal.py requires a POSIX host for its bounded process "
            "and filesystem safety contracts"
        )
        return
    candidate = shutil.which("git", path=os.environ.get("PATH"))
    if candidate is None:
        _GIT_RUNTIME_ERROR = UnsupportedGitVersion(
            "Git >= 2.45 is required, but no Git executable was found on PATH"
        )
        return
    try:
        executable = pathlib.Path(candidate).resolve(strict=True)
        executable_stat = executable.stat()
    except OSError as exc:
        _GIT_RUNTIME_ERROR = UnsupportedGitVersion(
            f"failed to resolve the selected Git executable: {exc}"
        )
        return
    if not stat.S_ISREG(executable_stat.st_mode) or not os.access(
        executable,
        os.X_OK,
    ):
        _GIT_RUNTIME_ERROR = UnsupportedGitVersion(
            f"selected Git executable is not an executable regular file: {executable}"
        )
        return

    try:
        (
            snapshot,
            digest,
            snapshot_identity,
            directory_identity,
            snapshot_owner,
        ) = _snapshot_git_executable(executable)
    except OSError as exc:
        _GIT_RUNTIME_ERROR = UnsupportedGitVersion(
            f"failed to create an owner-private Git runtime snapshot: {exc}"
        )
        return

    version_env = {
        key: os.environ[key]
        for key in (
            "LANG",
            "LC_ALL",
            "LC_CTYPE",
            "PATH",
            "SYSTEMROOT",
            "TEMP",
            "TMP",
            "TMPDIR",
        )
        if key in os.environ
    }
    version_env.update(SAFE_GIT_ENV)
    try:
        result = _capture_bounded_process(
            [str(snapshot), "--version"],
            env=version_env,
            timeout_seconds=GIT_VERSION_TIMEOUT_SECONDS,
            stdout_limit=MAX_GIT_VERSION_OUTPUT_BYTES,
            stderr_limit=MAX_GIT_VERSION_OUTPUT_BYTES,
            stdout_overflow_error=(
                f"Git version stdout exceeds {MAX_GIT_VERSION_OUTPUT_BYTES} bytes"
            ),
            stderr_overflow_error=(
                f"Git version stderr exceeds {MAX_GIT_VERSION_OUTPUT_BYTES} bytes"
            ),
            timeout_error=(
                f"Git version probe timed out after "
                f"{GIT_VERSION_TIMEOUT_SECONDS:g} seconds"
            ),
            operation="Git version probe",
        )
    except UserError as exc:
        snapshot_owner.cleanup()
        _GIT_RUNTIME_ERROR = UnsupportedGitVersion(
            f"failed the bounded credential-free Git version gate: {exc}"
        )
        return
    if result.returncode != 0:
        snapshot_owner.cleanup()
        detail = (
            result.stderr.decode("utf-8", errors="replace").strip()
            or result.stdout.decode("utf-8", errors="replace").strip()
            or f"exit {result.returncode}"
        )
        _GIT_RUNTIME_ERROR = UnsupportedGitVersion(
            f"Git version probe failed: {detail}"
        )
        return
    match = GIT_VERSION_RE.fullmatch(result.stdout)
    if match is None:
        snapshot_owner.cleanup()
        _GIT_RUNTIME_ERROR = UnsupportedGitVersion(
            "Git version probe returned an unsupported response"
        )
        return
    version = tuple(int(part or 0) for part in match.groups())
    if version < MINIMUM_GIT_VERSION:
        snapshot_owner.cleanup()
        actual = ".".join(str(part) for part in version)
        minimum = ".".join(str(part) for part in MINIMUM_GIT_VERSION[:2])
        _GIT_RUNTIME_ERROR = UnsupportedGitVersion(
            f"Git >= {minimum} is required; selected {executable} reports {actual}"
        )
        return
    _GIT_RUNTIME = _GitRuntime(
        executable=snapshot,
        source_executable=executable,
        version=version,
        digest=digest,
        file_identity=snapshot_identity,
        directory_identity=directory_identity,
        snapshot_owner=snapshot_owner,
    )
    try:
        _verify_git_runtime_snapshot(_GIT_RUNTIME)
    except UnsupportedGitVersion as exc:
        snapshot_owner.cleanup()
        _GIT_RUNTIME = None
        _GIT_RUNTIME_ERROR = exc


def _tracked_index_journal_snapshot(
    repo: pathlib.Path,
    *,
    deadline: float | None = None,
) -> tuple[bytes, list[IndexJournalBlob]]:
    parser = _IndexStageStreamParser()
    command = _git_command(
        repo,
        "ls-files",
        "--stage",
        "-z",
        "--",
        JOURNAL_ROOT.as_posix(),
    )
    timeout_error = (
        "tracked journal adoption validation exceeded its shared deadline"
        if deadline is not None
        else (
            "tracked journal index snapshot timed out after "
            f"{GIT_INDEX_SNAPSHOT_TIMEOUT_SECONDS:g} seconds"
        )
    )
    result = _capture_bounded_process(
        command,
        env=_git_environment(),
        timeout_seconds=GIT_INDEX_SNAPSHOT_TIMEOUT_SECONDS,
        stdout_limit=MAX_TRACKED_JOURNAL_INDEX_BYTES,
        stderr_limit=MAX_GIT_STDERR_BYTES,
        stdout_feed=parser.feed,
        stdout_finish=parser.finish,
        stdout_overflow_error=(
            "tracked journal index output exceeds "
            f"{MAX_TRACKED_JOURNAL_INDEX_BYTES} bytes"
        ),
        stderr_overflow_error=(
            f"git ls-files stderr exceeds {MAX_GIT_STDERR_BYTES} bytes"
        ),
        timeout_error=timeout_error,
        deadline=deadline,
    )
    if result.returncode != 0:
        detail = (
            result.stderr.decode("utf-8", errors="replace").strip()
            or result.stdout.decode("utf-8", errors="replace").strip()
            or "tracked journal lookup failed"
        )
        raise UserError(f"failed to list tracked journal entries: {detail}")
    return result.stdout, parser.blobs()


def _tracked_index_journal_blobs(repo: pathlib.Path) -> list[IndexJournalBlob]:
    _, blobs = _tracked_index_journal_snapshot(repo)
    return blobs


def _read_index_blobs_batch(
    repo: pathlib.Path,
    blobs: list[IndexJournalBlob],
    *,
    timeout_seconds: float = GIT_CAT_FILE_BATCH_TIMEOUT_SECONDS,
    deadline: float | None = None,
) -> list[bytes]:
    if not blobs:
        return []

    parser = _CatFileBatchStreamParser(blobs)
    request_data = parser.request_data()
    if len(request_data) > MAX_TRACKED_JOURNAL_BATCH_INPUT_BYTES:
        raise UserError(
            "tracked journal blob batch request exceeds "
            f"{MAX_TRACKED_JOURNAL_BATCH_INPUT_BYTES} bytes"
        )
    stdout_limit = min(
        MAX_TRACKED_JOURNAL_TOTAL_BYTES,
        len(blobs) * MAX_TRACKED_JOURNAL_BLOB_BYTES,
    ) + len(blobs) * (MAX_CAT_FILE_BATCH_HEADER_BYTES + 2)
    stdout_limit = min(
        stdout_limit,
        MAX_TRACKED_JOURNAL_BATCH_STDOUT_BYTES,
    )
    command = _git_command(repo, "cat-file", "--batch")
    timeout_error = (
        "tracked journal adoption validation exceeded its shared deadline"
        if deadline is not None
        else f"git cat-file batch timed out after {timeout_seconds:g} seconds"
    )
    result = _capture_bounded_process(
        command,
        env=_git_environment(),
        stdin_data=request_data,
        timeout_seconds=timeout_seconds,
        stdout_limit=stdout_limit,
        stderr_limit=MAX_GIT_STDERR_BYTES,
        stdout_feed=parser.feed,
        stdout_finish=parser.finish,
        stdout_overflow_error=(
            f"git cat-file batch stdout exceeds {stdout_limit} bytes"
        ),
        stderr_overflow_error=(
            f"git cat-file batch stderr exceeds {MAX_GIT_STDERR_BYTES} bytes"
        ),
        timeout_error=timeout_error,
        operation="Git cat-file batch",
        deadline=deadline,
    )
    if result.returncode != 0:
        detail = (
            result.stderr.decode("utf-8", errors="replace").strip()
            or "git cat-file batch failed"
        )
        raise UserError(f"failed to read tracked journal index blobs: {detail}")
    return parser.contents()


def _is_generated_index_blob(content: bytes) -> bool:
    lines = content.split(b"\n", 3)
    return (
        len(lines) >= 3
        and lines[0].removesuffix(b"\r") == b"# Project Journal Index"
        and lines[2].removesuffix(b"\r") == INDEX_GENERATED_LINE.encode("utf-8")
    )


def _is_generated_index(path: pathlib.Path) -> bool:
    try:
        content = path.read_bytes()
    except OSError:
        return False
    return _is_generated_index_blob(content)


def _load_entries_from_paths(
    repo: pathlib.Path, paths: list[pathlib.Path]
) -> tuple[list[JournalEntry], list[str]]:
    entries: list[JournalEntry] = []
    collector = _IssueCollector()
    if len(paths) > MAX_JOURNAL_ENTRIES:
        raise JournalLimitExceeded(f"journal entry count exceeds {MAX_JOURNAL_ENTRIES}")
    for path in paths:
        rel_path = path.relative_to(repo).as_posix()
        try:
            fields = _parse_frontmatter(path)
        except JournalLimitExceeded:
            raise
        except UserError as exc:
            collector.add(rel_path, str(exc))
            continue
        entries.append(JournalEntry(path=path, rel_path=rel_path, fields=fields))
    report = _validate_entries(entries, collector=collector)
    return entries, list(report.issues)


def _load_entries(repo: pathlib.Path) -> tuple[list[JournalEntry], list[str]]:
    return _load_entries_from_paths(repo, _journal_paths(repo))


def _load_entries_from_index(
    repo: pathlib.Path,
    *,
    timeout_seconds: float = GIT_ADOPTION_VALIDATION_TIMEOUT_SECONDS,
) -> tuple[list[JournalEntry], list[str], int]:
    loaded = _load_entries_from_index_report(
        repo,
        timeout_seconds=timeout_seconds,
    )
    return (
        list(loaded.entries),
        list(loaded.validation.issues),
        loaded.non_generated_count,
    )


def _load_entries_from_index_report(
    repo: pathlib.Path,
    *,
    timeout_seconds: float = GIT_ADOPTION_VALIDATION_TIMEOUT_SECONDS,
) -> _IndexedJournalLoad:
    if timeout_seconds <= 0:
        raise ValueError("timeout_seconds must be positive")
    entries: list[JournalEntry] = []
    collector = _IssueCollector()
    non_generated_count = 0
    validation_deadline = time.monotonic() + timeout_seconds
    deadline_error = "tracked journal adoption validation exceeded its shared deadline"
    initial_index, blobs = _tracked_index_journal_snapshot(
        repo,
        deadline=validation_deadline,
    )
    if len(blobs) > MAX_JOURNAL_ENTRIES:
        raise JournalLimitExceeded(
            f"tracked journal entry count exceeds {MAX_JOURNAL_ENTRIES}"
        )
    contents = _read_index_blobs_batch(
        repo,
        blobs,
        deadline=validation_deadline,
    )

    for blob, content in zip(blobs, contents):
        _check_deadline(validation_deadline, deadline_error)
        if _is_generated_index_blob(content):
            continue

        non_generated_count += 1
        try:
            text = content.decode("utf-8")
        except UnicodeDecodeError:
            collector.add(blob.rel_path, "index blob is not valid UTF-8")
            continue
        try:
            fields = _parse_frontmatter_text(
                text,
                blob.rel_path,
                deadline=validation_deadline,
                deadline_error=deadline_error,
            )
        except JournalLimitExceeded:
            raise
        except UserError as exc:
            collector.add(blob.rel_path, str(exc))
            continue
        entry_path = repo.joinpath(*pathlib.PurePosixPath(blob.rel_path).parts)
        entries.append(
            JournalEntry(
                path=entry_path,
                rel_path=blob.rel_path,
                fields=fields,
            )
        )

    report = _validate_entries(
        entries,
        deadline=validation_deadline,
        deadline_error=deadline_error,
        collector=collector,
    )
    final_index, _ = _tracked_index_journal_snapshot(
        repo,
        deadline=validation_deadline,
    )
    if final_index != initial_index:
        raise UserError("tracked journal Git index changed during validation")

    valid_count = 0
    for entry in entries:
        _check_deadline(validation_deadline, deadline_error)
        if entry.rel_path not in report.invalid_paths:
            valid_count += 1
    return _IndexedJournalLoad(
        entries=tuple(entries),
        validation=report,
        non_generated_count=non_generated_count,
        valid_count=valid_count,
    )


def _tracked_journal_adoption(repo: pathlib.Path) -> dict[str, Any]:
    loaded = _load_entries_from_index_report(repo)
    return {
        "tracked_journal_adopted": loaded.valid_count > 0,
        "tracked_non_generated_journal_count": loaded.non_generated_count,
        "valid_tracked_journal_count": loaded.valid_count,
    }


def _validate_date(value: str) -> bool:
    if not DATE_RE.match(value):
        return False
    try:
        dt.date.fromisoformat(value)
    except ValueError:
        return False
    return True


def _validate_entries(
    entries: list[JournalEntry],
    *,
    deadline: float | None = None,
    deadline_error: str = "journal validation exceeded its shared deadline",
    collector: _IssueCollector | None = None,
) -> _ValidationReport:
    if len(entries) > MAX_JOURNAL_ENTRIES:
        raise JournalLimitExceeded(f"journal entry count exceeds {MAX_JOURNAL_ENTRIES}")
    if collector is None:
        collector = _IssueCollector()
    id_groups: dict[str, list[JournalEntry]] = {}
    for entry in entries:
        _check_deadline(deadline, deadline_error)
        if entry.entry_id:
            id_groups.setdefault(entry.entry_id, []).append(entry)
    ids = {
        entry_id: grouped[0]
        for entry_id, grouped in id_groups.items()
        if len(grouped) == 1
    }
    rel_paths = {entry.rel_path for entry in entries}

    for entry in entries:
        _check_deadline(deadline, deadline_error)
        label = entry.rel_path
        for field in REQUIRED_FIELDS:
            _check_deadline(deadline, deadline_error)
            if field not in entry.fields:
                collector.add(label, f"missing required field {field!r}")

        if not entry.entry_id:
            collector.add(label, "field 'id' must not be empty")
        elif len(id_groups[entry.entry_id]) > 1:
            collector.add(label, f"duplicate id {entry.entry_id!r}")

        if not entry.title:
            collector.add(label, "field 'title' must not be empty")
        if entry.status not in VALID_STATUSES:
            collector.add(
                label,
                f"invalid status {entry.status!r}; "
                f"expected one of {', '.join(VALID_STATUSES)}",
            )
        if not entry.created:
            collector.add(label, "field 'created' must not be empty")
        elif not _validate_date(entry.created):
            collector.add(label, f"invalid created date {entry.created!r}")
        if not entry.updated:
            collector.add(label, "field 'updated' must not be empty")
        elif not _validate_date(entry.updated):
            collector.add(label, f"invalid updated date {entry.updated!r}")

    valid_targets = set(ids) | rel_paths
    for entry in entries:
        _check_deadline(deadline, deadline_error)
        for superseded in _as_list(
            entry.fields.get("supersedes"),
            label=entry.rel_path,
            field="supersedes",
            deadline=deadline,
            deadline_error=deadline_error,
        ):
            _check_deadline(deadline, deadline_error)
            if superseded not in valid_targets:
                collector.add(
                    entry.rel_path,
                    f"supersedes target {superseded!r} "
                    "does not match a journal id or path",
                )
        target = str(entry.fields.get("superseded_by", "")).strip()
        if target and target not in valid_targets:
            collector.add(
                entry.rel_path,
                f"superseded_by target {target!r} does not match a journal id or path",
            )
        if entry.status == "superseded":
            if not target:
                collector.add(
                    entry.rel_path,
                    "superseded entries must set 'superseded_by'",
                )

    return collector.report()


def _markdown_escape(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ").strip()


def _link_from_output(output_path: pathlib.Path, entry: JournalEntry) -> str:
    rel = os.path.relpath(entry.path, start=output_path.parent)
    return pathlib.PurePosixPath(rel).as_posix()


def _entry_sort_key(entry: JournalEntry) -> tuple[str, str, str]:
    return (entry.updated, entry.created, entry.title.lower())


def _render_index(
    repo: pathlib.Path, output_path: pathlib.Path, entries: list[JournalEntry]
) -> str:
    grouped = {status: [] for status in VALID_STATUSES}
    for entry in entries:
        if entry.status in grouped:
            grouped[entry.status].append(entry)
    for values in grouped.values():
        values.sort(key=_entry_sort_key, reverse=True)

    lines = [
        "# Project Journal Index",
        "",
        INDEX_GENERATED_LINE,
        "",
        "## Summary",
        "",
    ]
    for status in VALID_STATUSES:
        lines.append(f"- `{status}`: {len(grouped[status])}")
    lines.append("")

    if not entries:
        lines.extend(["No project journal entries found.", ""])
        return "\n".join(lines)

    for status in VALID_STATUSES:
        lines.extend([f"## {status.title()}", ""])
        if not grouped[status]:
            lines.extend(["_None._", ""])
            continue
        lines.append("| Updated | Title | ID | Branch | PR |")
        lines.append("| --- | --- | --- | --- | --- |")
        for entry in grouped[status]:
            href = _link_from_output(output_path, entry)
            title = _markdown_escape(entry.title)
            branch = _markdown_escape(str(entry.fields.get("branch", "")).strip())
            pr = _markdown_escape(str(entry.fields.get("pr", "")).strip())
            lines.append(
                f"| {entry.updated} | [{title}]({href}) | `{_markdown_escape(entry.entry_id)}` | {branch} | {pr} |"
            )
        lines.append("")
    return "\n".join(lines)


def _ensure_exclude(repo: pathlib.Path, output_rel: str) -> pathlib.Path:
    exclude_path = _git_path(repo, "info/exclude")
    exclude_path.parent.mkdir(parents=True, exist_ok=True)
    existing = exclude_path.read_text(encoding="utf-8") if exclude_path.exists() else ""
    lines = existing.splitlines()
    if output_rel not in lines:
        if existing and not existing.endswith("\n"):
            existing += "\n"
        existing += f"{output_rel}\n"
        exclude_path.write_text(existing, encoding="utf-8")
    return exclude_path


def command_generate(args: argparse.Namespace) -> int:
    repo = _resolve_repo(args.repo)
    output_rel = _to_repo_rel(repo, args.output)
    output_path = repo / output_rel
    entries, issues = _load_entries(repo)
    if issues:
        raise UserError(
            "journal validation failed before index generation:\n" + "\n".join(issues)
        )

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(_render_index(repo, output_path, entries), encoding="utf-8")
    if args.ensure_exclude:
        _ensure_exclude(repo, output_rel)
    print(output_path)
    return 0


def command_validate(args: argparse.Namespace) -> int:
    repo = _resolve_repo(args.repo)
    _entries, issues = _load_entries(repo)
    if issues:
        for issue in issues:
            print(issue, file=sys.stderr)
        return 1
    print("Project journal validation passed.")
    return 0


