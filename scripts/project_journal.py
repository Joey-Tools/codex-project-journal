def _lexical_absolute_path(
    path: pathlib.Path,
    *,
    base: pathlib.Path | None = None,
) -> pathlib.Path:
    if not path.is_absolute():
        if base is None:
            raise UserError(f"relative path has no trusted base: {path}")
        path = base / path
    return pathlib.Path(os.path.abspath(os.path.normpath(os.fspath(path))))


def _git_common_directory(repo: pathlib.Path) -> pathlib.Path:
    common_dir = _run_git(repo, "rev-parse", "--git-common-dir")
    if common_dir.returncode != 0 or not common_dir.stdout.strip():
        detail = (
            common_dir.stderr.strip()
            or common_dir.stdout.strip()
            or "Git common directory lookup failed"
        )
        raise UserError(f"failed to resolve Git common directory: {detail}")
    return _lexical_absolute_path(
        pathlib.Path(common_dir.stdout.strip()),
        base=repo,
    )


def _allowed_hook_roots(repo: pathlib.Path) -> list[pathlib.Path]:
    roots = [
        _lexical_absolute_path(repo),
        _lexical_absolute_path(_git_path(repo, "."), base=repo),
        _git_common_directory(repo),
    ]
    unique: list[pathlib.Path] = []
    for root in roots:
        if root not in unique:
            unique.append(root)
    return unique


def _hook_path_plan_from_config(repo: pathlib.Path, raw_path: str) -> _HookPathPlan:
    if raw_path == "":
        raise UserError(
            "core.hooksPath is empty; unset it or set a non-empty hook directory before installing"
        )
    if raw_path == os.devnull:
        raise UserError(
            "core.hooksPath points at os.devnull; cannot install project journal hooks"
        )
    # The scoped Git query has already applied Git's pathname expansion,
    # including ~ and %(prefix). Preserve every remaining path byte represented
    # by the decoded value; leading and trailing whitespace can be significant.
    hooks_dir = pathlib.Path(raw_path)
    hooks_dir = _lexical_absolute_path(hooks_dir, base=repo)
    candidates: list[tuple[pathlib.Path, tuple[str, ...]]] = []
    for root in _allowed_hook_roots(repo):
        try:
            relative = hooks_dir.relative_to(root)
        except ValueError:
            continue
        components = tuple(relative.parts)
        if any(component in {"", ".", ".."} for component in components):
            continue
        candidates.append((root, components))
    if not candidates:
        raise UserError(
            "core.hooksPath is outside the repository or Git directories; "
            "set a repo-local hook directory before installing"
        )
    root, components = max(candidates, key=lambda candidate: len(candidate[0].parts))
    return _HookPathPlan(root=root, components=components)


def _default_hook_path_plan(repo: pathlib.Path) -> _HookPathPlan:
    return _HookPathPlan(
        root=_git_common_directory(repo),
        components=("hooks",),
    )


def _global_git_config_paths() -> list[pathlib.Path]:
    override = os.environ.get("GIT_CONFIG_GLOBAL")
    if override is not None:
        if not override:
            raise UserError(
                "GIT_CONFIG_GLOBAL is empty; cannot prove the actual global "
                "core.hooksPath configuration safely"
            )
        if override == os.devnull:
            return []
        path = pathlib.Path(override).expanduser()
        if not path.is_absolute():
            path = pathlib.Path.cwd() / path
        return [_lexical_absolute_path(path)]

    home_text = os.environ.get("HOME")
    home = (
        pathlib.Path(home_text).expanduser()
        if home_text
        else pathlib.Path("~").expanduser()
    )
    xdg_text = os.environ.get("XDG_CONFIG_HOME")
    xdg = pathlib.Path(xdg_text).expanduser() if xdg_text else home / ".config"
    if not xdg.is_absolute():
        raise UserError(
            "XDG_CONFIG_HOME is relative; cannot prove the actual global "
            "core.hooksPath configuration safely"
        )
    return [
        _lexical_absolute_path(xdg / "git/config"),
        _lexical_absolute_path(home / ".gitconfig"),
    ]


def _parse_git_config_records(output: bytes, label: str) -> list[tuple[str, str]]:
    if output and not output.endswith(b"\0"):
        raise UserError(f"{label} returned malformed framing")
    try:
        records = [value.decode("utf-8") for value in output.split(b"\0") if value]
    except UnicodeDecodeError as exc:
        raise UserError(f"{label} returned non-UTF-8 data") from exc
    entries: list[tuple[str, str]] = []
    for record in records:
        key, separator, value = record.partition("\n")
        if not separator or not key:
            raise UserError(f"{label} returned malformed records")
        entries.append((key.lower(), value))
    return entries


def _parse_nul_terminated_git_path(output: bytes, label: str) -> str:
    if not output.endswith(b"\0") or b"\0" in output[:-1]:
        raise UserError(f"{label} returned malformed NUL framing")
    return os.fsdecode(output[:-1])


def _global_git_config_entries(
    config_path: pathlib.Path,
    *,
    missing_ok: bool = False,
    label: str = "global Git config",
) -> list[tuple[str, str]]:
    content = _secure_read_regular_path(
        config_path,
        label=label,
        byte_limit=MAX_GLOBAL_GIT_CONFIG_SOURCE_BYTES,
        missing_ok=missing_ok,
    )
    if content is None:
        return []

    with tempfile.NamedTemporaryFile(
        prefix="project-journal-global-config-",
        suffix=".cfg",
    ) as staged:
        staged.write(content)
        staged.flush()
        runtime = _require_git_runtime()
        command = [
            str(runtime.executable),
            "--no-pager",
            "--no-optional-locks",
            "config",
            "--file",
            staged.name,
            "--no-includes",
            "--null",
            "--list",
        ]
        result = _capture_bounded_process(
            command,
            env=_global_config_git_environment(),
            verified_runtime=runtime,
            timeout_seconds=GIT_CONFIG_QUERY_TIMEOUT_SECONDS,
            stdout_limit=MAX_GLOBAL_GIT_CONFIG_OUTPUT_BYTES,
            stderr_limit=MAX_GIT_STDERR_BYTES,
            stdout_overflow_error=(
                f"{label} query stdout exceeds "
                f"{MAX_GLOBAL_GIT_CONFIG_OUTPUT_BYTES} bytes"
            ),
            stderr_overflow_error=(
                f"{label} query stderr exceeds {MAX_GIT_STDERR_BYTES} bytes"
            ),
            timeout_error=(
                f"{label} query timed out after "
                f"{GIT_CONFIG_QUERY_TIMEOUT_SECONDS:g} seconds"
            ),
            operation=f"{label} query",
        )
    if result.returncode != 0:
        detail = (
            result.stderr.decode("utf-8", errors="replace").strip()
            or f"exit {result.returncode}"
        )
        raise UserError(f"failed to inspect {label} safely: {detail}")
    return _parse_git_config_records(result.stdout, f"{label} query")


def _git_env_flag_enabled(name: str) -> bool:
    value = os.environ.get(name)
    if value is None:
        return False
    return value.strip().lower() not in {"0", "false", "no", "off"}


def _system_git_config_entries() -> list[tuple[str, str]]:
    if _git_env_flag_enabled("GIT_CONFIG_NOSYSTEM"):
        return []

    configured_path = os.environ.get("GIT_CONFIG_SYSTEM")
    if configured_path is not None:
        if not configured_path:
            raise UserError(
                "GIT_CONFIG_SYSTEM is empty; cannot prove the actual system "
                "core.hooksPath configuration safely"
            )
        path = pathlib.Path(configured_path)
        if not path.is_absolute():
            raise UserError(
                "GIT_CONFIG_SYSTEM must be an absolute path so its system Git "
                "config identity can be proved safely"
            )
        path = _lexical_absolute_path(path)
        if path == _lexical_absolute_path(pathlib.Path(os.devnull)):
            return []
        return _global_git_config_entries(path, label="system Git config")

    raise UserError(
        "implicit system Git config path cannot be proved safely without "
        "following an unbound pathname; set GIT_CONFIG_SYSTEM to an absolute "
        "regular-file path or set GIT_CONFIG_NOSYSTEM=1"
    )


def _preflight_global_hooks_config(repo: pathlib.Path) -> None:
    system_entries = _system_git_config_entries()
    system_hooks = [value for key, value in system_entries if key == "core.hookspath"]
    system_includes = [
        key
        for key, _value in system_entries
        if key == "include.path"
        or (key.startswith("includeif.") and key.endswith(".path"))
    ]
    # The verified runtime snapshot is process-private and disappears at exit.
    # Remediation text must instead name the durable source path selected for it.
    git_executable = shlex.quote(str(_require_git_runtime().source_executable))
    repo_arg = shlex.quote(str(repo))
    instruction = (
        f"{git_executable} -C {repo_arg} config --local core.hooksPath .githooks"
    )
    if system_hooks:
        raise UserError(
            "system core.hooksPath is set, so installing into the default "
            "repository hook directory would not be used by actual Git; "
            f"set an explicit repo-local override first, for example: {instruction}"
        )
    if system_includes:
        raise UserError(
            "system Git config contains include directives; project_journal.py "
            "does not follow system includes while resolving core.hooksPath, so "
            "the effective hook directory cannot be proved safely; set an explicit "
            f"repo-local override first, for example: {instruction}"
        )

    entries: list[tuple[str, str]] = []
    for config_path in _global_git_config_paths():
        entries.extend(_global_git_config_entries(config_path, missing_ok=True))
    hooks_values = [value for key, value in entries if key == "core.hookspath"]
    include_keys = [
        key
        for key, _value in entries
        if key == "include.path"
        or (key.startswith("includeif.") and key.endswith(".path"))
    ]
    if not hooks_values and not include_keys:
        return

    if hooks_values:
        raise UserError(
            "global core.hooksPath is set, so installing into the default "
            "repository hook directory would not be used by actual Git; "
            f"set an explicit repo-local override first, for example: {instruction}"
        )
    raise UserError(
        "global Git config contains include directives; project_journal.py "
        "does not follow global includes while resolving core.hooksPath, so "
        "the effective hook directory cannot be proved safely; set an explicit "
        f"repo-local override first, for example: {instruction}"
    )


def _hook_path_plan(repo: pathlib.Path) -> _HookPathPlan:
    for scope in ("--worktree", "--local"):
        operation = f"{scope} core.hooksPath query"
        command = _git_command(
            repo,
            "config",
            "--includes",
            scope,
            "--type=path",
            "--null",
            "--get",
            "core.hooksPath",
        )
        configured = _capture_bounded_process(
            command,
            env=_git_environment(),
            verified_runtime=_require_git_runtime(),
            timeout_seconds=GIT_CONFIG_QUERY_TIMEOUT_SECONDS,
            stdout_limit=MAX_GLOBAL_GIT_CONFIG_OUTPUT_BYTES,
            stderr_limit=MAX_GIT_STDERR_BYTES,
            stdout_overflow_error=(
                f"{operation} stdout exceeds {MAX_GLOBAL_GIT_CONFIG_OUTPUT_BYTES} bytes"
            ),
            stderr_overflow_error=(
                f"{operation} stderr exceeds {MAX_GIT_STDERR_BYTES} bytes"
            ),
            timeout_error=(
                f"{operation} timed out after "
                f"{GIT_CONFIG_QUERY_TIMEOUT_SECONDS:g} seconds"
            ),
            operation=operation,
        )
        if configured.returncode == 0:
            raw_path = _parse_nul_terminated_git_path(
                configured.stdout,
                operation,
            )
            return _hook_path_plan_from_config(repo, raw_path)
        if configured.returncode != 1:
            detail = (
                configured.stderr.decode("utf-8", errors="replace").strip()
                or f"exit {configured.returncode}"
            )
            raise UserError(
                f"failed to resolve {scope} core.hooksPath safely: {detail}"
            )
    _preflight_global_hooks_config(repo)
    return _default_hook_path_plan(repo)


def _hook_path(repo: pathlib.Path, name: str) -> pathlib.Path:
    return _hook_path_plan(repo).path / name


def _validate_hook_directory_stat(
    path: pathlib.Path,
    value: os.stat_result,
    *,
    require_access_policy: bool = True,
) -> tuple[int, int, int, int, int]:
    if not stat.S_ISDIR(value.st_mode):
        raise UserError(f"hook directory is not a directory: {path}")
    mode = stat.S_IMODE(value.st_mode)
    if require_access_policy and (value.st_uid != os.geteuid() or mode & 0o022):
        raise UserError(
            f"hook directory must be owned by the current user and not "
            f"group/world writable: {path}"
        )
    return _directory_identity(value)


def _revalidate_hook_directory(binding: _HookDirectoryBinding) -> None:
    for ancestor in binding.ancestors:
        try:
            descriptor_stat = os.fstat(ancestor.fd)
            descriptor_identity = _validate_hook_directory_stat(
                ancestor.path,
                descriptor_stat,
                require_access_policy=ancestor.access_policy_required,
            )
            if ancestor.parent_fd is None:
                path_stat = os.stat(ancestor.path, follow_symlinks=False)
                path_identity = _validate_hook_directory_stat(
                    ancestor.path,
                    path_stat,
                    require_access_policy=ancestor.access_policy_required,
                )
            else:
                assert ancestor.component is not None
                path_stat = os.stat(
                    ancestor.component,
                    dir_fd=ancestor.parent_fd,
                    follow_symlinks=False,
                )
                path_identity = _validate_hook_directory_stat(
                    ancestor.path,
                    path_stat,
                    require_access_policy=ancestor.access_policy_required,
                )
            if ancestor.access_policy_required:
                _reject_extended_acl(
                    ancestor.fd,
                    ancestor.path,
                    "hook path ancestor",
                )
        except OSError as exc:
            raise UserError(
                f"hook path ancestor became unavailable during installation: "
                f"{ancestor.path}: {exc}"
            ) from exc
        if (
            descriptor_identity != ancestor.identity
            or path_identity != ancestor.identity
        ):
            raise UserError(
                f"hook path ancestor identity or access policy changed during "
                f"installation: {ancestor.path}"
            )
    _revalidate_hook_install_lock(binding)


def _hook_target_identity(value: os.stat_result) -> tuple[int, ...]:
    """Bind hook object/type, owner/group/mode policy, and content size."""
    return (
        value.st_dev,
        value.st_ino,
        stat.S_IFMT(value.st_mode),
        value.st_uid,
        value.st_gid,
        stat.S_IMODE(value.st_mode),
        value.st_size,
    )


def _snapshot_hook_target(
    binding: _HookDirectoryBinding,
    name: str,
) -> tuple[_HookTargetSnapshot, bytes | None]:
    flags = (
        os.O_RDONLY
        | getattr(os, "O_CLOEXEC", 0)
        | _required_open_flag("O_NOFOLLOW")
        | _required_open_flag("O_NONBLOCK")
    )
    try:
        fd = os.open(name, flags, dir_fd=binding.fd)
    except FileNotFoundError:
        return _HookTargetSnapshot(name=name, exists=False), None
    except OSError as exc:
        if exc.errno in {errno.ELOOP, errno.EMLINK}:
            raise UserError(
                f"{binding.path / name} is a symlink; refusing to overwrite hook links"
            ) from exc
        raise UserError(
            f"failed to open hook target {binding.path / name}: {exc}"
        ) from exc

    try:
        before = os.fstat(fd)
        if not stat.S_ISREG(before.st_mode):
            raise UserError(f"hook target is not a regular file: {binding.path / name}")
        _reject_extended_acl(
            fd,
            binding.path / name,
            "hook target",
        )
        if before.st_size > MAX_EXISTING_HOOK_BYTES:
            raise UserError(
                f"hook target exceeds {MAX_EXISTING_HOOK_BYTES} bytes: "
                f"{binding.path / name}"
            )
        content = bytearray()
        while len(content) <= MAX_EXISTING_HOOK_BYTES:
            chunk = os.read(
                fd,
                min(
                    PROCESS_READ_CHUNK_BYTES,
                    MAX_EXISTING_HOOK_BYTES + 1 - len(content),
                ),
            )
            if not chunk:
                break
            content.extend(chunk)
        after = os.fstat(fd)
        _reject_extended_acl(
            fd,
            binding.path / name,
            "hook target",
        )
        linked = os.stat(name, dir_fd=binding.fd, follow_symlinks=False)
    finally:
        os.close(fd)
    if len(content) > MAX_EXISTING_HOOK_BYTES:
        raise UserError(
            f"hook target exceeds {MAX_EXISTING_HOOK_BYTES} bytes: "
            f"{binding.path / name}"
        )
    identity = _hook_target_identity(before)
    if (
        _hook_target_identity(after) != identity
        or _hook_target_identity(linked) != identity
    ):
        raise UserError(
            f"hook target identity changed while being inspected: {binding.path / name}"
        )
    raw = bytes(content)
    return (
        _HookTargetSnapshot(
            name=name,
            exists=True,
            identity=identity,
            digest=hashlib.sha256(raw).hexdigest(),
        ),
        raw,
    )


def _validate_managed_hook(path: pathlib.Path, content: bytes) -> None:
    existing = content.decode("utf-8", errors="replace")
    if HOOK_BEGIN not in existing or HOOK_END not in existing:
        raise UserError(
            f"{path} already exists and is not managed by project_journal.py"
        )
    before, _marker, rest = existing.partition(HOOK_BEGIN)
    _managed, _end_marker, after = rest.partition(HOOK_END)
    before_lines = [line for line in before.splitlines() if line.strip()]
    if before_lines not in ([], ["#!/bin/sh"]) or after.strip():
        raise UserError(
            f"{path} contains unmanaged content outside the project journal marker block"
        )


def _revalidate_hook_target(
    binding: _HookDirectoryBinding,
    expected: _HookTargetSnapshot,
) -> None:
    actual, _content = _snapshot_hook_target(binding, expected.name)
    if actual != expected:
        raise UserError(
            f"hook target changed after preflight: {binding.path / expected.name}"
        )


def _bind_hook_directory(plan: _HookPathPlan) -> _HookDirectoryBinding:
    if os.name != "posix":
        raise UserError(
            "project journal hook installation requires POSIX descriptor-relative "
            "filesystem primitives"
        )
    flags = (
        os.O_RDONLY
        | getattr(os, "O_DIRECTORY", 0)
        | getattr(os, "O_CLOEXEC", 0)
        | _required_open_flag("O_NOFOLLOW")
    )
    opened: list[_BoundHookDirectory] = []
    try:
        if not plan.root.is_absolute() or plan.root.anchor != os.sep:
            raise UserError(
                f"allowed hook root is not an absolute POSIX path: {plan.root}"
            )
        filesystem_root = pathlib.Path(os.sep)
        root_fd = os.open(filesystem_root, flags)
        root_identity = _validate_hook_directory_stat(
            filesystem_root,
            os.fstat(root_fd),
            require_access_policy=False,
        )
        root_path_identity = _validate_hook_directory_stat(
            filesystem_root,
            os.stat(filesystem_root, follow_symlinks=False),
            require_access_policy=False,
        )
        if root_identity != root_path_identity:
            os.close(root_fd)
            raise UserError(
                f"filesystem root changed while hook path was being bound: "
                f"{filesystem_root}"
            )
        opened.append(
            _BoundHookDirectory(
                path=filesystem_root,
                fd=root_fd,
                identity=root_identity,
                parent_fd=None,
                component=None,
                access_policy_required=False,
            )
        )
        current = opened[0]
        root_components = plan.root.parts[1:]
        traversal = (
            *(
                (component, False, index == len(root_components) - 1)
                for index, component in enumerate(root_components)
            ),
            *((component, True, True) for component in plan.components),
        )
        for component, may_create, access_policy_required in traversal:
            component_path = current.path / component
            child_fd: int | None = None
            try:
                child_fd = os.open(component, flags, dir_fd=current.fd)
            except FileNotFoundError:
                if not may_create:
                    raise
                try:
                    os.mkdir(component, 0o755, dir_fd=current.fd)
                except FileExistsError:
                    pass
                child_fd = os.open(component, flags, dir_fd=current.fd)
            try:
                child_identity = _validate_hook_directory_stat(
                    component_path,
                    os.fstat(child_fd),
                    require_access_policy=access_policy_required,
                )
                linked_identity = _validate_hook_directory_stat(
                    component_path,
                    os.stat(
                        component,
                        dir_fd=current.fd,
                        follow_symlinks=False,
                    ),
                    require_access_policy=access_policy_required,
                )
                if child_identity != linked_identity:
                    raise UserError(
                        f"hook path component changed while being bound: "
                        f"{component_path}"
                    )
                if access_policy_required:
                    _reject_extended_acl(
                        child_fd,
                        component_path,
                        "hook path component",
                    )
            except BaseException:
                os.close(child_fd)
                raise
            current = _BoundHookDirectory(
                path=component_path,
                fd=child_fd,
                identity=child_identity,
                parent_fd=current.fd,
                component=component,
                access_policy_required=access_policy_required,
            )
            opened.append(current)
    except OSError as exc:
        for ancestor in reversed(opened):
            os.close(ancestor.fd)
        raise UserError(
            f"failed descriptor-relative hook path traversal under {plan.root}: {exc}"
        ) from exc
    except BaseException:
        for ancestor in reversed(opened):
            os.close(ancestor.fd)
        raise

    final = opened[-1]
    binding = _HookDirectoryBinding(
        path=final.path,
        fd=final.fd,
        identity=final.identity,
        ancestors=tuple(opened),
        targets=(),
    )
    try:
        _revalidate_hook_directory(binding)
    except BaseException:
        _close_hook_binding(binding)
        raise
    return binding


def _close_hook_binding(binding: _HookDirectoryBinding) -> None:
    if binding.install_lock_fd is not None:
        try:
            os.close(binding.install_lock_fd)
        except OSError:
            pass
    for ancestor in reversed(binding.ancestors):
        try:
            os.close(ancestor.fd)
        except OSError:
            pass


def _revalidate_hook_install_lock(binding: _HookDirectoryBinding) -> None:
    if binding.install_lock_fd is None:
        return
    if binding.install_lock_identity is None:
        raise UserError("hook installation lock identity is missing")
    name = ".project-journal-install.lock"
    try:
        descriptor_stat = os.fstat(binding.install_lock_fd)
        path_stat = os.stat(name, dir_fd=binding.fd, follow_symlinks=False)
        _reject_extended_acl(
            binding.install_lock_fd,
            binding.path / name,
            "hook installation lock",
        )
    except OSError as exc:
        raise UserError(
            f"hook installation lock became unavailable: {binding.path / name}: {exc}"
        ) from exc
    if (
        not stat.S_ISREG(descriptor_stat.st_mode)
        or _file_identity(descriptor_stat) != binding.install_lock_identity
        or _file_identity(path_stat) != binding.install_lock_identity
        or descriptor_stat.st_uid != os.geteuid()
        or stat.S_IMODE(descriptor_stat.st_mode) != 0o600
    ):
        raise UserError(
            f"hook installation lock identity or access policy changed: "
            f"{binding.path / name}"
        )


def _acquire_hook_install_lock(
    binding: _HookDirectoryBinding,
) -> _HookDirectoryBinding:
    try:
        import fcntl
    except ImportError as exc:
        raise UnsupportedPlatform(
            "hook installation requires POSIX advisory file locking"
        ) from exc

    name = ".project-journal-install.lock"
    flags = (
        os.O_RDWR
        | os.O_CREAT
        | getattr(os, "O_CLOEXEC", 0)
        | _required_open_flag("O_NOFOLLOW")
        | _required_open_flag("O_NONBLOCK")
    )
    try:
        fd = os.open(name, flags, 0o600, dir_fd=binding.fd)
    except OSError as exc:
        raise UserError(
            f"failed to open hook installation lock {binding.path / name}: {exc}"
        ) from exc
    try:
        descriptor_stat = os.fstat(fd)
        path_stat = os.stat(name, dir_fd=binding.fd, follow_symlinks=False)
        descriptor_identity = _file_identity(descriptor_stat)
        _reject_extended_acl(
            fd,
            binding.path / name,
            "hook installation lock",
        )
        if (
            not stat.S_ISREG(descriptor_stat.st_mode)
            or descriptor_identity != _file_identity(path_stat)
            or descriptor_stat.st_uid != os.geteuid()
            or stat.S_IMODE(descriptor_stat.st_mode) != 0o600
        ):
            raise UserError(
                f"hook installation lock is not an owner-private regular file: "
                f"{binding.path / name}"
            )
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise UserError(
                f"another project journal hook installation is active: {binding.path}"
            ) from exc
        descriptor_after = os.fstat(fd)
        path_after = os.stat(name, dir_fd=binding.fd, follow_symlinks=False)
        _reject_extended_acl(
            fd,
            binding.path / name,
            "hook installation lock",
        )
        if (
            _file_identity(descriptor_after) != descriptor_identity
            or _file_identity(path_after) != descriptor_identity
        ):
            raise UserError(
                f"hook installation lock identity changed while being acquired: "
                f"{binding.path / name}"
            )
    except BaseException:
        os.close(fd)
        raise
    return dataclasses.replace(
        binding,
        install_lock_fd=fd,
        install_lock_identity=descriptor_identity,
    )


def _preflight_hook_targets(repo: pathlib.Path) -> _HookDirectoryBinding:
    binding = _bind_hook_directory(_hook_path_plan(repo))
    try:
        binding = _acquire_hook_install_lock(binding)
        provisional = dataclasses.replace(
            binding,
            targets=(),
        )
        targets: list[_HookTargetSnapshot] = []
        for name in HOOK_NAMES:
            target, content = _snapshot_hook_target(provisional, name)
            if content is not None:
                _validate_managed_hook(binding.path / name, content)
            targets.append(target)
        binding = dataclasses.replace(provisional, targets=tuple(targets))
        _revalidate_hook_directory(binding)
        return binding
    except BaseException:
        _close_hook_binding(binding)
        raise


def _write_all(fd: int, content: bytes) -> None:
    offset = 0
    while offset < len(content):
        written = os.write(fd, content[offset:])
        if written <= 0:
            raise OSError("short write while staging hook")
        offset += written


def _rename_hook_entry_with_flag(
    directory_fd: int,
    source: str,
    destination: str,
    *,
    exchange: bool,
) -> None:
    if os.name != "posix" or not (
        sys.platform == "darwin" or sys.platform.startswith("linux")
    ):
        raise UnsupportedPlatform(
            "atomic hook installation is supported only on macOS and Linux"
        )
    library = ctypes.CDLL(None, use_errno=True)
    source_bytes = os.fsencode(source)
    destination_bytes = os.fsencode(destination)
    if sys.platform == "darwin":
        try:
            rename_function = library.renameatx_np
        except AttributeError as exc:
            raise UserError(
                "atomic hook installation is unavailable: renameatx_np is missing"
            ) from exc
        rename_function.argtypes = (
            ctypes.c_int,
            ctypes.c_char_p,
            ctypes.c_int,
            ctypes.c_char_p,
            ctypes.c_uint,
        )
        rename_function.restype = ctypes.c_int
        flag = 0x00000002 if exchange else 0x00000004
    elif sys.platform.startswith("linux"):
        try:
            rename_function = library.renameat2
        except AttributeError as exc:
            raise UserError(
                "atomic hook installation is unavailable: renameat2 is missing"
            ) from exc
        rename_function.argtypes = (
            ctypes.c_int,
            ctypes.c_char_p,
            ctypes.c_int,
            ctypes.c_char_p,
            ctypes.c_uint,
        )
        rename_function.restype = ctypes.c_int
        flag = 0x00000002 if exchange else 0x00000001
    ctypes.set_errno(0)
    result = rename_function(
        directory_fd,
        source_bytes,
        directory_fd,
        destination_bytes,
        flag,
    )
    if result != 0:
        error_number = ctypes.get_errno() or errno.EIO
        raise OSError(
            error_number,
            os.strerror(error_number),
            destination,
        )


def _rollback_hook_exchange(
    binding: _HookDirectoryBinding,
    temporary_name: str,
    target_name: str,
) -> str | None:
    try:
        _rename_hook_entry_with_flag(
            binding.fd,
            temporary_name,
            target_name,
            exchange=True,
        )
        os.fsync(binding.fd)
    except (OSError, UserError) as exc:
        return str(exc)
    return None


def _hook_recovery_exception_evidence(error: BaseException) -> dict[str, object]:
    evidence: dict[str, object] = {"type": type(error).__name__}
    candidates = (error, error.__cause__, error.__context__)
    for candidate in candidates:
        error_number = getattr(candidate, "errno", None)
        if isinstance(error_number, int):
            evidence["errno"] = error_number
            error_name = errno.errorcode.get(error_number)
            if error_name is not None:
                evidence["error_name"] = error_name
            break
    return evidence


def _hook_recovery_exception_summary(error: BaseException) -> str:
    evidence = _hook_recovery_exception_evidence(error)
    summary = str(evidence["type"])
    if "errno" in evidence:
        summary += f" errno={evidence['errno']}"
    if "error_name" in evidence:
        summary += f" ({evidence['error_name']})"
    return summary


def _hook_leaf_identity_evidence(
    identity: tuple[int, ...],
    digest: str | None,
) -> dict[str, object]:
    evidence: dict[str, object] = {
        "device": identity[0],
        "inode": identity[1],
        "type": f"0o{identity[2]:o}",
        "uid": identity[3],
        "gid": identity[4],
        "mode": f"0o{identity[5]:03o}",
        "size": identity[6],
    }
    if digest is not None:
        evidence["digest"] = digest
    return evidence


def _bound_hook_child_component(
    parent: _BoundHookDirectory,
    child: _BoundHookDirectory,
) -> tuple[str | None, str | None]:
    if child.component is None or child.parent_fd != parent.fd:
        return None, "bound ancestor parent relationship is invalid"

    def matches(name: str) -> bool:
        try:
            value = os.stat(
                name,
                dir_fd=parent.fd,
                follow_symlinks=False,
            )
        except OSError:
            return False
        if not stat.S_ISDIR(value.st_mode):
            return False
        try:
            identity = _validate_hook_directory_stat(
                pathlib.Path(name),
                value,
                require_access_policy=child.access_policy_required,
            )
        except UserError:
            return False
        return identity == child.identity

    if matches(child.component):
        return child.component, None

    matched: list[str] = []
    try:
        with os.scandir(parent.fd) as entries:
            for index, entry in enumerate(entries, start=1):
                if index > MAX_HOOK_RECOVERY_PATH_SCAN_ENTRIES:
                    return (
                        None,
                        "bound parent directory exceeds the recovery path "
                        f"scan limit of {MAX_HOOK_RECOVERY_PATH_SCAN_ENTRIES} entries",
                    )
                name = os.fsdecode(entry.name)
                if name == child.component:
                    continue
                if matches(name):
                    matched.append(name)
                    if len(matched) > 1:
                        return (
                            None,
                            "bound ancestor has multiple descriptor-relative "
                            "names under its held parent",
                        )
    except OSError as exc:
        return (
            None,
            "bound parent directory scan failed: "
            f"{_hook_recovery_exception_summary(exc)}",
        )
    if not matched:
        return (
            None,
            "bound ancestor is no longer a descriptor-relative entry of its "
            "held parent",
        )
    return matched[0], None


def _resolve_bound_hook_directory_path(
    binding: _HookDirectoryBinding,
) -> tuple[pathlib.Path | None, str | None]:
    if not binding.ancestors:
        return None, "hook directory ancestor binding is empty"
    resolved = pathlib.Path(os.sep)
    for index, ancestor in enumerate(binding.ancestors):
        descriptor_label = pathlib.Path(f"<held-hook-ancestor-{index}>")
        try:
            descriptor_identity = _validate_hook_directory_stat(
                descriptor_label,
                os.fstat(ancestor.fd),
                require_access_policy=ancestor.access_policy_required,
            )
            if ancestor.access_policy_required:
                _reject_extended_acl(
                    ancestor.fd,
                    descriptor_label,
                    "recovery hook path ancestor",
                )
        except BaseException as exc:
            return (
                None,
                f"held ancestor {index} revalidation failed or is unreadable: "
                f"{_hook_recovery_exception_summary(exc)}",
            )
        if descriptor_identity != ancestor.identity:
            return (
                None,
                f"held ancestor {index} object identity or access policy changed",
            )
        if index == 0:
            try:
                root_identity = _validate_hook_directory_stat(
                    pathlib.Path(os.sep),
                    os.stat(os.sep, follow_symlinks=False),
                    require_access_policy=False,
                )
            except BaseException as exc:
                return (
                    None,
                    "filesystem root revalidation failed or is unreadable: "
                    f"{_hook_recovery_exception_summary(exc)}",
                )
            if root_identity != ancestor.identity:
                return None, "filesystem root object identity changed"
            continue
        component, error = _bound_hook_child_component(
            binding.ancestors[index - 1],
            ancestor,
        )
        if component is None:
            return None, f"held ancestor {index} path is unverified: {error}"
        resolved /= component
    if binding.fd != binding.ancestors[-1].fd:
        return None, "hook directory descriptor does not match its final ancestor"
    return resolved, None


def _hook_recovery_reference(
    binding: _HookDirectoryBinding,
    temporary_name: str,
    expected: _HookTargetSnapshot,
) -> str:
    evidence: dict[str, Any] = {
        "leaf": temporary_name,
        "path_status": "path_unverified",
    }
    reasons: list[str] = []
    try:
        directory_stat = os.fstat(binding.fd)
        raw_directory_identity = _directory_identity(directory_stat)
        evidence["directory"] = {
            "device": raw_directory_identity[0],
            "inode": raw_directory_identity[1],
            "uid": raw_directory_identity[2],
            "gid": raw_directory_identity[3],
            "mode": f"0o{raw_directory_identity[4]:03o}",
        }
        directory_identity = _validate_hook_directory_stat(
            pathlib.Path("<held-hook-directory>"),
            directory_stat,
        )
        _reject_extended_acl(
            binding.fd,
            pathlib.Path("<held-hook-directory>"),
            "recovery hook directory",
        )
    except BaseException as exc:
        evidence["directory_status"] = "unreadable"
        evidence["directory_error"] = _hook_recovery_exception_evidence(exc)
        reasons.append(
            "held hook directory revalidation failed or is unreadable: "
            f"{_hook_recovery_exception_summary(exc)}"
        )
    else:
        if directory_identity != binding.identity:
            evidence["directory_status"] = "mismatched"
            reasons.append("held hook directory identity or access policy changed")
        else:
            evidence["directory_status"] = "verified"

    recovered: _HookTargetSnapshot | None = None
    try:
        recovered, _recovered_content = _snapshot_hook_target(
            binding,
            temporary_name,
        )
    except BaseException as exc:
        evidence["held_object_status"] = "unreadable"
        evidence["held_object_error"] = _hook_recovery_exception_evidence(exc)
        reasons.append(
            "descriptor-relative recovery leaf revalidation failed or is "
            f"unreadable: {_hook_recovery_exception_summary(exc)}"
        )
        try:
            observed_stat = os.stat(
                temporary_name,
                dir_fd=binding.fd,
                follow_symlinks=False,
            )
        except FileNotFoundError:
            evidence["leaf_observation_status"] = "missing"
        except OSError as observation_error:
            evidence["leaf_observation_status"] = "unreadable"
            evidence["leaf_observation_error"] = _hook_recovery_exception_evidence(
                observation_error
            )
        else:
            evidence["leaf_observation_status"] = "observed"
            evidence["leaf_identity"] = _hook_leaf_identity_evidence(
                _hook_target_identity(observed_stat),
                None,
            )
    else:
        if not recovered.exists:
            evidence["held_object_status"] = "missing"
            reasons.append("descriptor-relative recovery leaf is missing")
        else:
            assert recovered.identity is not None
            evidence["leaf_identity"] = _hook_leaf_identity_evidence(
                recovered.identity,
                recovered.digest,
            )
            if recovered == expected:
                evidence["held_object_status"] = "verified"
            else:
                evidence["held_object_status"] = "mismatched"
                reasons.append(
                    _hook_snapshot_match_status(
                        recovered,
                        expected,
                        "descriptor-relative recovery leaf",
                    )
                )

    first_path, first_error = _resolve_bound_hook_directory_path(binding)
    if first_path is None:
        reasons.append(first_error or "first ancestor-chain resolution failed")
    if (
        first_path is not None
        and recovered is not None
        and recovered.exists
        and evidence.get("directory_status") == "verified"
    ):
        second_path, second_error = _resolve_bound_hook_directory_path(binding)
        if second_path != first_path:
            reasons.append(
                second_error
                or "bound ancestor chain changed during recovery-leaf validation"
            )
        else:
            recovery_path = second_path / temporary_name
            try:
                path_stat = os.stat(recovery_path, follow_symlinks=False)
            except OSError as exc:
                reasons.append(
                    "resolved recovery leaf became unavailable: "
                    f"{_bounded_signal_report_detail(exc)}"
                )
            else:
                if _hook_target_identity(path_stat) != recovered.identity:
                    reasons.append(
                        "resolved recovery leaf does not bind the held object identity"
                    )
                else:
                    final_path, final_error = _resolve_bound_hook_directory_path(
                        binding
                    )
                    if final_path != second_path:
                        reasons.append(
                            final_error
                            or "bound ancestor chain changed after recovery-leaf "
                            "path validation"
                        )
                    else:
                        try:
                            rebound, _rebound_content = _snapshot_hook_target(
                                binding,
                                temporary_name,
                            )
                        except BaseException as exc:
                            reasons.append(
                                "final descriptor-relative recovery leaf "
                                "revalidation failed or is unreadable: "
                                f"{_hook_recovery_exception_summary(exc)}"
                            )
                        else:
                            confirmed_path, confirmed_error = (
                                _resolve_bound_hook_directory_path(binding)
                            )
                            if rebound != recovered:
                                reasons.append(
                                    "descriptor-relative recovery leaf changed "
                                    "during path validation"
                                )
                            elif confirmed_path != final_path:
                                reasons.append(
                                    confirmed_error
                                    or "bound ancestor chain changed during final "
                                    "recovery-leaf revalidation"
                                )
                            else:
                                try:
                                    confirmed_stat = os.stat(
                                        recovery_path,
                                        follow_symlinks=False,
                                    )
                                except OSError as exc:
                                    reasons.append(
                                        "resolved recovery leaf became unavailable "
                                        "after final descriptor-relative "
                                        "revalidation: "
                                        f"{_bounded_signal_report_detail(exc)}"
                                    )
                                else:
                                    if (
                                        _hook_target_identity(confirmed_stat)
                                        != rebound.identity
                                    ):
                                        reasons.append(
                                            "resolved recovery leaf changed after "
                                            "final descriptor-relative "
                                            "revalidation"
                                        )
                                    else:
                                        evidence["path_status"] = "path_verified"
                                        evidence["path"] = str(recovery_path)

    if reasons:
        evidence["reason"] = "; ".join(reasons)
    encoded = json.dumps(
        evidence,
        ensure_ascii=True,
        sort_keys=True,
        separators=(",", ":"),
    )
    if evidence["path_status"] == "path_verified":
        return (
            f"preserved recovery locator: {evidence['path']}; "
            f"recovery_evidence={encoded}"
        )
    if evidence.get("held_object_status") == "verified":
        return (
            "preserved recovery object with path_unverified; "
            f"recovery_evidence={encoded}"
        )
    return f"recovery path_unverified; recovery_evidence={encoded}"


def _hook_temporary_cleanup_reference(
    binding: _HookDirectoryBinding,
    temporary_name: str,
) -> str:
    try:
        expected, _content = _snapshot_hook_target(
            binding,
            temporary_name,
        )
    except BaseException:
        expected = _HookTargetSnapshot(
            name=temporary_name,
            exists=False,
        )
    try:
        return _hook_recovery_reference(
            binding,
            temporary_name,
            expected,
        )
    except BaseException as recovery_error:
        evidence = {
            "leaf": temporary_name,
            "path_status": "path_unverified",
            "reference_error": _hook_recovery_exception_evidence(recovery_error),
        }
        return "recovery path_unverified; recovery_evidence=" + json.dumps(
            evidence,
            ensure_ascii=True,
            sort_keys=True,
            separators=(",", ":"),
        )


def _cleanup_hook_temporary_entry(
    binding: _HookDirectoryBinding,
    temporary_name: str,
    active_error: BaseException | None,
) -> None:
    try:
        os.unlink(temporary_name, dir_fd=binding.fd)
    except FileNotFoundError:
        return
    except BaseException as cleanup_error:
        recovery = _hook_temporary_cleanup_reference(
            binding,
            temporary_name,
        )
        locator_status = (
            "descriptor-bound/path-verified"
            if recovery.startswith("preserved recovery locator:")
            else "descriptor-relative/path-unverified"
        )
        recovery_issue = (
            "hook temporary-entry cleanup-incomplete; "
            f"{locator_status} recovery evidence: {recovery}"
        )
        cleanup_issue = (
            "hook temporary-entry unlink failed with "
            f"{_hook_recovery_exception_summary(cleanup_error)}: "
            f"{_bounded_signal_report_detail(cleanup_error)}"
        )
        cleanup_notes = tuple(
            detail
            for detail in getattr(cleanup_error, "__notes__", ())
            if isinstance(detail, str)
        )
        if active_error is not None:
            _add_exception_details(
                active_error,
                (recovery_issue, cleanup_issue, *cleanup_notes),
            )
            return
        if isinstance(cleanup_error, Exception):
            failure = UserError(
                _bounded_signal_report_detail(recovery_issue),
            )
            _add_exception_details(
                failure,
                (cleanup_issue, *cleanup_notes),
            )
            raise failure from cleanup_error
        _add_exception_details(
            cleanup_error,
            (recovery_issue, cleanup_issue),
        )
        raise


def _recovery_error(
    binding: _HookDirectoryBinding,
    temporary_name: str,
    expected: _HookTargetSnapshot,
    detail: str,
) -> _HookExchangeRecoveryRequired:
    try:
        os.fsync(binding.fd)
    except OSError as exc:
        detail = f"{detail}; directory fsync failed: {exc}"
    recovery = _hook_recovery_reference(
        binding,
        temporary_name,
        expected,
    )
    return _HookExchangeRecoveryRequired(
        f"hook exchange state is uncertain and cleanup is incomplete: "
        f"{detail}; {recovery}",
        temporary_name,
    )


def _interrupted_hook_exchange_recovery_note(
    binding: _HookDirectoryBinding,
    target: _HookTargetSnapshot,
    temporary_name: str,
) -> str:
    durability_error: str | None = None
    try:
        os.fsync(binding.fd)
    except BaseException as exc:
        durability_error = str(exc)

    expected = dataclasses.replace(target, name=temporary_name)
    try:
        recovered, _content = _snapshot_hook_target(binding, temporary_name)
    except BaseException as exc:
        verification = f"recovery identity is unverified: {exc}"
    else:
        if recovered == expected:
            verification = (
                "descriptor-relative displaced-hook identity, content, and "
                "access policy remain verified"
            )
        else:
            verification = (
                "descriptor-relative recovery leaf does not match the displaced hook"
            )
    if durability_error is not None:
        verification += f"; directory durability is unverified: {durability_error}"
    recovery = _hook_recovery_reference(
        binding,
        temporary_name,
        expected,
    )
    return f"hook exchange may have committed; {verification}; {recovery}"


def _hook_snapshot_match_status(
    actual: _HookTargetSnapshot,
    expected: _HookTargetSnapshot,
    subject: str,
) -> str:
    if not actual.exists:
        return f"{subject} is missing"
    if actual == expected:
        return f"{subject} remains object-identity/content/access-policy verified"

    mismatches: list[str] = []
    if actual.identity is None or expected.identity is None:
        mismatches.append("object identity")
    else:
        if actual.identity[:3] != expected.identity[:3]:
            mismatches.append("object identity/type")
        if actual.identity[3:6] != expected.identity[3:6]:
            mismatches.append("ownership/access policy")
        if actual.identity[6] != expected.identity[6]:
            mismatches.append("content size")
    if actual.digest != expected.digest:
        mismatches.append("content digest")
    if not mismatches:
        mismatches.append("snapshot metadata")
    return f"{subject} mismatches its expected bound snapshot ({', '.join(mismatches)})"


