def _revalidate_failed_absent_hook_rename(
    binding: _HookDirectoryBinding,
    target: _HookTargetSnapshot,
    temporary_name: str,
    staged: _HookTargetSnapshot,
    rename_error: OSError,
) -> str:
    target_snapshot: _HookTargetSnapshot | None = None
    temporary_snapshot: _HookTargetSnapshot | None = None
    target_error: Exception | None = None
    temporary_error: Exception | None = None
    try:
        target_snapshot, _target_content = _snapshot_hook_target(
            binding,
            target.name,
        )
    except Exception as exc:
        target_error = exc
    try:
        temporary_snapshot, _temporary_content = _snapshot_hook_target(
            binding,
            temporary_name,
        )
    except Exception as exc:
        temporary_error = exc

    if (
        target_error is None
        and temporary_error is None
        and target_snapshot == target
        and temporary_snapshot == staged
    ):
        return "uncommitted"

    expected_installed = dataclasses.replace(staged, name=target.name)
    expected_consumed = _HookTargetSnapshot(name=temporary_name, exists=False)
    if (
        target_error is None
        and temporary_error is None
        and target_snapshot == expected_installed
        and temporary_snapshot == expected_consumed
    ):
        return "committed"

    if target_error is not None:
        target_status = f"target revalidation failed or is unreadable: {target_error}"
    else:
        assert target_snapshot is not None
        target_status = _hook_snapshot_match_status(
            target_snapshot,
            expected_installed,
            "installed target",
        )
    if temporary_error is not None:
        temporary_status = (
            f"staged-temporary revalidation failed or is unreadable: {temporary_error}"
        )
    else:
        assert temporary_snapshot is not None
        temporary_status = _hook_snapshot_match_status(
            temporary_snapshot,
            staged,
            "staged temporary",
        )
    raise _uncertain_absent_hook_rename_error(
        binding,
        temporary_name,
        staged,
        f"atomic no-replace rename reported {rename_error}; {target_status}; "
        f"{temporary_status}",
    ) from rename_error


def _interrupted_absent_hook_commit_note(
    binding: _HookDirectoryBinding,
    target: _HookTargetSnapshot,
    temporary_name: str,
    staged: _HookTargetSnapshot,
) -> str:
    durability_error: str | None = None
    recovery: str | None = None
    try:
        os.fsync(binding.fd)
    except BaseException as exc:
        durability_error = str(exc)

    expected_installed = dataclasses.replace(staged, name=target.name)
    installed_matches = False
    try:
        installed, _installed_content = _snapshot_hook_target(
            binding,
            target.name,
        )
    except BaseException as exc:
        installed_status = (
            f"installed-target revalidation failed or is unreadable: {exc}"
        )
    else:
        installed_status = _hook_snapshot_match_status(
            installed,
            expected_installed,
            "installed target",
        )
        installed_matches = installed == expected_installed

    temporary_missing = False
    try:
        temporary, _temporary_content = _snapshot_hook_target(
            binding,
            temporary_name,
        )
    except BaseException as exc:
        temporary_status = (
            f"staged-temporary revalidation failed or is unreadable: {exc}"
        )
    else:
        if not temporary.exists:
            temporary_missing = True
            temporary_status = (
                "transaction temporary was consumed; no displaced-hook "
                "recovery object exists"
            )
        elif temporary == staged:
            temporary_status = "staged temporary remains after interrupted cleanup"
            recovery = _hook_recovery_reference(
                binding,
                temporary_name,
                staged,
            )
        else:
            temporary_status = (
                "temporary entry mismatches the staged hook; no displaced-hook "
                "recovery object or path is claimed"
            )

    commit_status = (
        "absent-target no-replace rename committed"
        if installed_matches and temporary_missing
        else "absent-target no-replace rename may have committed"
    )
    detail = f"{commit_status}; {installed_status}; {temporary_status}"
    if durability_error is not None:
        detail += f"; directory durability is unverified: {durability_error}"
    if recovery is not None:
        detail += f"; {recovery}"
    return detail


def _interrupted_hook_post_commit_note(
    binding: _HookDirectoryBinding,
    target: _HookTargetSnapshot,
    temporary_name: str,
    staged: _HookTargetSnapshot,
) -> str:
    durability_error: str | None = None
    recovery: str | None = None
    try:
        os.fsync(binding.fd)
    except BaseException as exc:
        durability_error = str(exc)

    expected_installed = dataclasses.replace(staged, name=target.name)
    try:
        installed, _installed_content = _snapshot_hook_target(
            binding,
            target.name,
        )
    except BaseException as exc:
        installed_status = (
            f"installed-target revalidation failed or is unreadable: {exc}"
        )
    else:
        installed_status = _hook_snapshot_match_status(
            installed,
            expected_installed,
            "installed target",
        )

    try:
        temporary, _temporary_content = _snapshot_hook_target(
            binding,
            temporary_name,
        )
    except BaseException as exc:
        cleanup_status = f"temporary-entry revalidation failed or is unreadable: {exc}"
    else:
        if target.exists:
            expected_temporary = dataclasses.replace(target, name=temporary_name)
            if not temporary.exists:
                cleanup_status = (
                    "displaced-hook cleanup completed; transaction temporary "
                    "was consumed and no recovery object exists"
                )
            elif temporary == expected_temporary:
                cleanup_status = "displaced-hook cleanup was interrupted"
                recovery = _hook_recovery_reference(
                    binding,
                    temporary_name,
                    expected_temporary,
                )
            else:
                cleanup_status = (
                    "temporary entry mismatches the verified displaced hook; "
                    "no recovery identity or path is claimed"
                )
        else:
            if not temporary.exists:
                cleanup_status = (
                    "transaction temporary was consumed by the committed "
                    "no-replace rename; no displaced-hook recovery object exists"
                )
            elif temporary == staged:
                cleanup_status = "staged temporary unexpectedly remains after commit"
                recovery = _hook_recovery_reference(
                    binding,
                    temporary_name,
                    staged,
                )
            else:
                cleanup_status = (
                    "temporary entry mismatches the staged hook; no "
                    "displaced-hook recovery object or path is claimed"
                )

    detail = (
        f"hook installation reached the installed-target-committed state; "
        f"{installed_status}; {cleanup_status}"
    )
    if durability_error is not None:
        detail += f"; directory durability is unverified: {durability_error}"
    if recovery is not None:
        detail += f"; {recovery}"
    return detail


def _revalidate_failed_hook_exchange(
    binding: _HookDirectoryBinding,
    target: _HookTargetSnapshot,
    temporary_name: str,
    staged: _HookTargetSnapshot,
    exchange_error: OSError,
) -> None:
    target_snapshot: _HookTargetSnapshot | None = None
    temporary_snapshot: _HookTargetSnapshot | None = None
    target_error: Exception | None = None
    temporary_error: Exception | None = None
    try:
        target_snapshot, _target_content = _snapshot_hook_target(
            binding,
            target.name,
        )
    except Exception as exc:
        target_error = exc
    try:
        temporary_snapshot, _temporary_content = _snapshot_hook_target(
            binding,
            temporary_name,
        )
    except Exception as exc:
        temporary_error = exc

    # Cleanup is authorized only when object identity, exact content, and
    # owner/group/mode access policy prove that the exchange did not occur.
    if (
        target_error is None
        and temporary_error is None
        and target_snapshot == target
        and temporary_snapshot == staged
    ):
        return

    expected_installed = dataclasses.replace(staged, name=target.name)
    expected_displaced = dataclasses.replace(target, name=temporary_name)
    if target_error is not None:
        target_status = f"target revalidation failed or is unreadable: {target_error}"
    else:
        assert target_snapshot is not None
        target_status = _hook_snapshot_match_status(
            target_snapshot,
            expected_installed,
            "installed target",
        )
    if temporary_error is not None:
        temporary_status = (
            "transaction-temporary revalidation failed or is unreadable: "
            f"{temporary_error}"
        )
    else:
        assert temporary_snapshot is not None
        temporary_status = _hook_snapshot_match_status(
            temporary_snapshot,
            expected_displaced,
            "displaced-hook recovery object",
        )
    raise _recovery_error(
        binding,
        temporary_name,
        expected_displaced,
        f"atomic exchange reported {exchange_error}; {target_status}; "
        f"{temporary_status}",
    ) from exchange_error


def _commit_hook_target_atomically(
    binding: _HookDirectoryBinding,
    target: _HookTargetSnapshot,
    temporary_name: str,
    staged: _HookTargetSnapshot,
    commit_state: _HookCommitState,
) -> None:
    _raise_if_termination_pending()
    if not target.exists:
        commit_state.begin_absent_rename()
        try:
            _rename_hook_entry_with_flag(
                binding.fd,
                temporary_name,
                target.name,
                exchange=False,
            )
            _raise_if_termination_pending()
        except OSError as exc:
            if exc.errno in {errno.EEXIST, errno.ENOTEMPTY}:
                commit_state.mark_cleanup_safe()
                raise UserError(
                    f"hook target changed at atomic commit: "
                    f"{binding.path / target.name}"
                ) from exc
            rename_status = _revalidate_failed_absent_hook_rename(
                binding,
                target,
                temporary_name,
                staged,
                exc,
            )
            if rename_status == "committed":
                commit_state.mark_installed_target_committed("directory durability")
                commit_state.mark_temporary_consumed()
                return
            if rename_status != "uncommitted":
                raise RuntimeError(
                    f"unexpected absent-target rename status {rename_status!r}"
                )
            commit_state.mark_cleanup_safe()
            raise
        commit_state.mark_installed_target_committed("directory durability")
        commit_state.mark_temporary_consumed()
        return

    commit_state.begin_exchange()
    try:
        _rename_hook_entry_with_flag(
            binding.fd,
            temporary_name,
            target.name,
            exchange=True,
        )
        _raise_if_termination_pending()
    except OSError as exc:
        _revalidate_failed_hook_exchange(
            binding,
            target,
            temporary_name,
            staged,
            exc,
        )
        commit_state.mark_cleanup_safe()
        if exc.errno in {errno.ENOENT, errno.EEXIST, errno.ENOTEMPTY}:
            raise UserError(
                f"hook target changed at atomic commit: {binding.path / target.name}"
            ) from exc
        raise

    expected_displaced = dataclasses.replace(target, name=temporary_name)
    try:
        displaced, _content = _snapshot_hook_target(binding, temporary_name)
    except BaseException as exc:
        raise _recovery_error(
            binding,
            temporary_name,
            expected_displaced,
            f"the displaced entry could not be inspected: {exc}",
        ) from exc

    if displaced == expected_displaced:
        try:
            installed, _installed_content = _snapshot_hook_target(
                binding,
                target.name,
            )
        except BaseException as exc:
            raise _recovery_error(
                binding,
                temporary_name,
                expected_displaced,
                f"the installed target could not be verified before cleanup: {exc}",
            ) from exc
        expected_installed = dataclasses.replace(staged, name=target.name)
        if installed != expected_installed:
            raise _recovery_error(
                binding,
                temporary_name,
                expected_displaced,
                "the installed target does not match the staged hook before cleanup",
            )
        commit_state.mark_installed_target_committed("displaced-hook cleanup")
        os.unlink(temporary_name, dir_fd=binding.fd)
        _raise_if_termination_pending()
        commit_state.mark_temporary_consumed()
        return

    mismatch = UserError(
        f"hook target changed at atomic commit: {binding.path / target.name}"
    )
    try:
        installed, _installed_content = _snapshot_hook_target(
            binding,
            target.name,
        )
    except BaseException as ownership_exc:
        raise _recovery_error(
            binding,
            temporary_name,
            expected_displaced,
            f"the installed target could not be rebound: {ownership_exc}",
        ) from mismatch
    expected_installed = dataclasses.replace(staged, name=target.name)
    if installed != expected_installed:
        raise _recovery_error(
            binding,
            temporary_name,
            expected_displaced,
            "the installed target is no longer owned by this transaction",
        ) from mismatch
    rollback_error = _rollback_hook_exchange(
        binding,
        temporary_name,
        target.name,
    )
    if rollback_error is not None:
        raise _recovery_error(
            binding,
            temporary_name,
            expected_displaced,
            rollback_error,
        ) from mismatch
    try:
        rollback_staged, _rollback_content = _snapshot_hook_target(
            binding,
            temporary_name,
        )
        restored, _restored_content = _snapshot_hook_target(
            binding,
            target.name,
        )
    except BaseException as verification_exc:
        raise _recovery_error(
            binding,
            temporary_name,
            staged,
            f"rollback result could not be inspected: {verification_exc}",
        ) from mismatch
    expected_restored = dataclasses.replace(displaced, name=target.name)
    if rollback_staged != staged or restored != expected_restored:
        raise _recovery_error(
            binding,
            temporary_name,
            staged,
            "rollback result could not be bound to the staged and displaced objects",
        ) from mismatch
    commit_state.mark_cleanup_safe()
    raise mismatch


def _install_hook(
    binding: _HookDirectoryBinding,
    target: _HookTargetSnapshot,
) -> pathlib.Path:
    _raise_if_termination_pending()
    _revalidate_hook_directory(binding)
    _revalidate_hook_target(binding, target)
    content = _hook_body().encode("utf-8")
    temporary_name = f".project-journal-{target.name}-{secrets.token_hex(12)}.tmp"
    flags = (
        os.O_WRONLY
        | os.O_CREAT
        | os.O_EXCL
        | getattr(os, "O_CLOEXEC", 0)
        | _required_open_flag("O_NOFOLLOW")
        | _required_open_flag("O_NONBLOCK")
    )
    temporary_created = False
    commit_state = _HookCommitState()
    try:
        temporary_fd = os.open(temporary_name, flags, 0o600, dir_fd=binding.fd)
        temporary_created = True
        try:
            _write_all(temporary_fd, content)
            os.fsync(temporary_fd)
            os.fchmod(temporary_fd, 0o755)
            os.fsync(temporary_fd)
        finally:
            os.close(temporary_fd)
        staged, staged_content = _snapshot_hook_target(binding, temporary_name)
        if (
            not staged.exists
            or staged_content != content
            or staged.identity is None
            or staged.identity[5] != 0o755
        ):
            raise UserError(
                f"staged hook failed verification: {binding.path / temporary_name}"
            )
        _revalidate_hook_directory(binding)
        _revalidate_hook_target(binding, target)
        _raise_if_termination_pending()
        _commit_hook_target_atomically(
            binding,
            target,
            temporary_name,
            staged,
            commit_state,
        )
        temporary_created = False
        _raise_if_termination_pending()
        os.fsync(binding.fd)
        commit_state.mark_directory_durable()
        _raise_if_termination_pending()
        _revalidate_hook_directory(binding)
        installed, installed_content = _snapshot_hook_target(binding, target.name)
        expected_installed = dataclasses.replace(staged, name=target.name)
        if installed != expected_installed or installed_content != content:
            status = _hook_snapshot_match_status(
                installed,
                expected_installed,
                "installed target",
            )
            if installed == expected_installed and installed_content != content:
                status = (
                    "installed target mismatches the committed staged hook "
                    "(exact content bytes)"
                )
            raise UserError(
                f"hook target failed post-write verification: "
                f"{binding.path / target.name}: {status}"
            )
        commit_state.mark_verified()
        _raise_if_termination_pending()
    except _HookExchangeRecoveryRequired:
        temporary_created = False
        raise
    except OSError as exc:
        if commit_state.absent_rename_may_have_committed:
            temporary_created = False
            detail = _interrupted_absent_hook_commit_note(
                binding,
                target,
                temporary_name,
                staged,
            )
            raise UserError(
                f"absent-target hook rename may have committed: {exc}; {detail}"
            ) from exc
        if commit_state.must_preserve_temporary:
            temporary_created = False
            durability_detail = ""
            try:
                os.fsync(binding.fd)
            except OSError as fsync_exc:
                durability_detail = f"; directory fsync failed: {fsync_exc}"
            expected_recovery = dataclasses.replace(
                target,
                name=temporary_name,
            )
            recovery = _hook_recovery_reference(
                binding,
                temporary_name,
                expected_recovery,
            )
            raise UserError(
                f"hook exchange may have committed{durability_detail}; {recovery}"
            ) from exc
        if commit_state.installed_target_committed:
            temporary_created = False
            detail = _interrupted_hook_post_commit_note(
                binding,
                target,
                temporary_name,
                staged,
            )
            pending_step = commit_state.pending_step or "post-commit verification"
            raise UserError(
                f"hook target installation committed, but {pending_step} is "
                f"incomplete: "
                f"{exc}; {detail}"
            ) from exc
        raise UserError(
            f"failed to install hook {binding.path / target.name}: {exc}"
        ) from exc
    except Exception as exc:
        if commit_state.installed_target_committed:
            temporary_created = False
            detail = _interrupted_hook_post_commit_note(
                binding,
                target,
                temporary_name,
                staged,
            )
            pending_step = commit_state.pending_step or "post-commit verification"
            raise UserError(
                f"hook target installation committed, but {pending_step} is "
                f"incomplete: "
                f"{exc}; {detail}"
            ) from exc
        raise
    except BaseException as exc:
        if commit_state.absent_rename_may_have_committed:
            temporary_created = False
            detail = _interrupted_absent_hook_commit_note(
                binding,
                target,
                temporary_name,
                staged,
            )
            _add_exception_detail(exc, detail)
        elif commit_state.must_preserve_temporary:
            temporary_created = False
            detail = _interrupted_hook_exchange_recovery_note(
                binding,
                target,
                temporary_name,
            )
            _add_exception_detail(exc, detail)
        elif commit_state.installed_target_committed:
            temporary_created = False
            detail = _interrupted_hook_post_commit_note(
                binding,
                target,
                temporary_name,
                staged,
            )
            pending_step = commit_state.pending_step or "post-commit verification"
            _add_exception_detail(
                exc,
                f"hook target installation committed, but {pending_step} "
                f"is incomplete after interruption; {detail}",
            )
        raise
    finally:
        if temporary_created:
            _cleanup_hook_temporary_entry(
                binding,
                temporary_name,
                sys.exc_info()[1],
            )
    return binding.path / target.name


def command_install_hooks(args: argparse.Namespace) -> int:
    repo = _resolve_repo(args.repo)
    binding = _preflight_hook_targets(repo)
    try:
        _ensure_exclude(repo, DEFAULT_INDEX.as_posix())
        _revalidate_hook_directory(binding)
        installed = [_install_hook(binding, target) for target in binding.targets]
    finally:
        _close_hook_binding(binding)
    for path in installed:
        print(path)
    return 0


@dataclasses.dataclass
class _DiscoveryScanState:
    deadline: float
    scan_entries: int = 0
    rollouts_scanned: int = 0
    total_bytes: int = 0
    records_scanned: int = 0
    distinct_cwds: set[str] = dataclasses.field(default_factory=set)

    def check_deadline(self) -> None:
        _raise_if_termination_pending()
        if time.monotonic() >= self.deadline:
            raise DiscoveryDeadlineExceeded(
                "repository discovery exceeded its one shared "
                f"{DISCOVERY_TIMEOUT_SECONDS:g}-second deadline"
            )

    @staticmethod
    def _check_limit(
        limit_name: str,
        value: int,
        limit: int,
    ) -> None:
        if value > limit:
            raise DiscoveryLimitExceeded(limit_name, limit, value)

    def add_scan_entry(self) -> None:
        self.check_deadline()
        self.scan_entries += 1
        self._check_limit(
            "filesystem entry count",
            self.scan_entries,
            MAX_DISCOVERY_SCAN_ENTRIES,
        )

    def add_rollout(self) -> None:
        self.check_deadline()
        self.rollouts_scanned += 1
        self._check_limit(
            "rollout count",
            self.rollouts_scanned,
            MAX_DISCOVERY_ROLLOUTS,
        )

    def add_record(self, byte_count: int) -> None:
        self.check_deadline()
        self.total_bytes += byte_count
        self._check_limit(
            "total rollout bytes",
            self.total_bytes,
            MAX_DISCOVERY_TOTAL_BYTES,
        )
        self.records_scanned += 1
        self._check_limit(
            "rollout record count",
            self.records_scanned,
            MAX_DISCOVERY_RECORDS,
        )

    def add_cwd(self, cwd: str) -> None:
        if cwd in self.distinct_cwds:
            return
        observed = len(self.distinct_cwds) + 1
        self._check_limit(
            "distinct CWD count",
            observed,
            MAX_DISCOVERY_DISTINCT_CWDS,
        )
        self.distinct_cwds.add(cwd)

    def coverage_counters(self) -> dict[str, int]:
        return {
            "filesystem_entries_scanned": self.scan_entries,
            "rollouts_scanned": self.rollouts_scanned,
            "rollout_bytes_scanned": self.total_bytes,
            "rollout_records_scanned": self.records_scanned,
            "distinct_cwds_scanned": len(self.distinct_cwds),
        }


def _path_date(path: pathlib.Path) -> dt.date | None:
    parts = path.parts
    for index, part in enumerate(parts):
        if part in {"sessions", "archived_sessions"} and index + 3 < len(parts):
            try:
                return dt.date(
                    int(parts[index + 1]),
                    int(parts[index + 2]),
                    int(parts[index + 3]),
                )
            except ValueError:
                continue
    if "archived_sessions" in parts:
        match = ARCHIVED_ROLLOUT_DATE_RE.match(path.name)
        if match is not None:
            try:
                return dt.date(*(int(value) for value in match.groups()))
            except ValueError:
                return None
    return None


def _rollout_last_seen(path: pathlib.Path) -> str:
    dated = _path_date(path)
    if dated is not None:
        return dated.isoformat()
    mtime = dt.datetime.fromtimestamp(path.stat().st_mtime, tz=dt.timezone.utc)
    return mtime.date().isoformat()


def _rollout_in_window(path: pathlib.Path, cutoff: dt.date) -> bool:
    dated = _path_date(path)
    if dated is not None:
        return dated >= cutoff
    mtime = dt.datetime.fromtimestamp(path.stat().st_mtime, tz=dt.timezone.utc)
    return mtime.date() >= cutoff


def _iter_rollout_paths(
    root: pathlib.Path,
    state: _DiscoveryScanState,
) -> Iterable[pathlib.Path]:
    state.check_deadline()
    try:
        root_stat = os.stat(root)
    except FileNotFoundError:
        try:
            os.lstat(root)
        except FileNotFoundError:
            return
        raise
    if not stat.S_ISDIR(root_stat.st_mode):
        raise NotADirectoryError(
            errno.ENOTDIR,
            "Codex rollout root is not a directory",
            str(root),
        )

    pending = [root]
    while pending:
        state.check_deadline()
        directory = pending.pop()
        with os.scandir(directory) as entries:
            for entry in entries:
                state.add_scan_entry()
                try:
                    entry_stat = entry.stat(follow_symlinks=False)
                except FileNotFoundError:
                    continue
                if stat.S_ISDIR(entry_stat.st_mode):
                    pending.append(pathlib.Path(entry.path))
                    continue
                if (
                    stat.S_ISREG(entry_stat.st_mode)
                    and entry.name.startswith("rollout-")
                    and entry.name.endswith(".jsonl")
                ):
                    yield pathlib.Path(entry.path)


def _check_json_depth(raw_record: bytes) -> None:
    depth = 0
    in_string = False
    escaped = False
    for byte in raw_record:
        if in_string:
            if escaped:
                escaped = False
            elif byte == 0x5C:
                escaped = True
            elif byte == 0x22:
                in_string = False
            continue
        if byte == 0x22:
            in_string = True
        elif byte in {0x5B, 0x7B}:
            depth += 1
            if depth > MAX_DISCOVERY_JSON_DEPTH:
                raise DiscoveryLimitExceeded(
                    "JSON nesting depth",
                    MAX_DISCOVERY_JSON_DEPTH,
                    depth,
                )
        elif byte in {0x5D, 0x7D} and depth:
            depth -= 1


def _walk_for_cwds(value: Any) -> Iterable[str]:
    pending = [value]
    cwd_keys = {
        "cwd",
        "workdir",
        "working_dir",
        "working_directory",
    }
    while pending:
        item = pending.pop()
        if isinstance(item, dict):
            for key, child in item.items():
                if key in cwd_keys and isinstance(child, str):
                    yield child
                else:
                    pending.append(child)
        elif isinstance(item, list):
            pending.extend(item)


def _extract_cwds(
    rollout: pathlib.Path,
    state: _DiscoveryScanState,
) -> Iterable[str]:
    with rollout.open("rb") as handle:
        while True:
            state.check_deadline()
            line = handle.readline(MAX_DISCOVERY_LINE_BYTES + 1)
            if not line:
                return
            if len(line) > MAX_DISCOVERY_LINE_BYTES:
                raise DiscoveryLimitExceeded(
                    "rollout line bytes",
                    MAX_DISCOVERY_LINE_BYTES,
                    len(line),
                )
            state.add_record(len(line))
            stripped = line.strip()
            if not stripped:
                continue
            _check_json_depth(stripped)
            try:
                payload = json.loads(stripped.decode("utf-8", errors="replace"))
            except json.JSONDecodeError:
                continue
            except RecursionError as exc:
                raise DiscoveryLimitExceeded(
                    "JSON nesting depth",
                    MAX_DISCOVERY_JSON_DEPTH,
                    MAX_DISCOVERY_JSON_DEPTH + 1,
                ) from exc
            yield from _walk_for_cwds(payload)


def _normalize_discovery_cwd(cwd: str) -> str:
    """Deduplicate harmless spelling aliases without resolving symlinks or `..`."""

    return os.fspath(pathlib.Path(cwd))


def _known_source_root_from_temp_path(path: pathlib.Path) -> pathlib.Path | None:
    parts = path.parts
    for index, part in enumerate(parts):
        if part != ".codex-tmp" or index + 2 >= len(parts):
            continue
        temp_name = parts[index + 1]
        workspace_name = parts[index + 2]
        if temp_name.startswith("isolated-review-") and workspace_name == "workspace":
            source = pathlib.Path(*parts[:index])
            return source if source != pathlib.Path() else pathlib.Path("/")
    return None


def _is_relative_to(path: pathlib.Path, parent: pathlib.Path) -> bool:
    try:
        _lexical_absolute_path(path).relative_to(_lexical_absolute_path(parent))
    except ValueError:
        return False
    return True


def _git_output_path(repo: pathlib.Path, raw_path: str) -> pathlib.Path:
    path = pathlib.Path(raw_path.strip())
    return _lexical_absolute_path(path, base=repo)


def _source_root_from_linked_worktree(
    repo: pathlib.Path,
    *,
    deadline: float | None = None,
) -> pathlib.Path | None:
    deadline_error = "repository discovery exceeded its shared deadline"
    try:
        git_dir = _run_git(
            repo,
            "rev-parse",
            "--git-dir",
            deadline=deadline,
            deadline_error=deadline_error,
            operation="Git repository discovery",
        )
        common_dir = _run_git(
            repo,
            "rev-parse",
            "--git-common-dir",
            deadline=deadline,
            deadline_error=deadline_error,
            operation="Git repository discovery",
        )
    except UnsupportedGitVersion:
        return None
    if git_dir.returncode != 0 or common_dir.returncode != 0:
        return None

    git_dir_path = _git_output_path(repo, git_dir.stdout)
    common_dir_path = _git_output_path(repo, common_dir.stdout)
    if git_dir_path == common_dir_path:
        return None

    source = (
        common_dir_path.parent if common_dir_path.name == ".git" else common_dir_path
    )
    source_root = _repo_root_for_existing_path(source, deadline=deadline)
    if source_root is None or source_root == repo:
        return None
    return source_root


def _filesystem_repo_root(path: pathlib.Path) -> pathlib.Path | None:
    candidate = path if path.is_dir() else path.parent
    while True:
        git_marker = candidate / ".git"
        if git_marker.is_dir() or git_marker.is_file():
            return _lexical_absolute_path(candidate)
        parent = candidate.parent
        if parent == candidate:
            return None
        candidate = parent


def _repo_root_for_existing_path(
    path: pathlib.Path,
    *,
    deadline: float | None = None,
) -> pathlib.Path | None:
    deadline_error = "repository discovery exceeded its shared deadline"
    while not path.exists():
        _check_deadline(deadline, deadline_error)
        parent = path.parent
        if parent == path:
            return None
        path = parent
    try:
        result = _run_git(
            path,
            "rev-parse",
            "--show-toplevel",
            deadline=deadline,
            deadline_error=deadline_error,
            operation="Git repository discovery",
        )
    except UnsupportedGitVersion:
        return _filesystem_repo_root(path)
    if result.returncode != 0:
        return None
    return _lexical_absolute_path(pathlib.Path(result.stdout.strip()))


def _repo_root_for_path(
    path_text: str,
    *,
    codex_home: pathlib.Path | None = None,
    deadline: float | None = None,
) -> pathlib.Path | None:
    path = pathlib.Path(path_text).expanduser()
    if not path.is_absolute():
        return None
    source = _known_source_root_from_temp_path(path)
    if source is not None:
        source_root = _repo_root_for_existing_path(source, deadline=deadline)
        if source_root is not None:
            return source_root
    root = _repo_root_for_existing_path(path, deadline=deadline)
    if root is None:
        return None
    if codex_home is not None and _is_relative_to(root, codex_home / "worktrees"):
        source_root = _source_root_from_linked_worktree(root, deadline=deadline)
        if source_root is not None:
            return source_root
    return root


def _has_hook_marker(repo: pathlib.Path) -> bool:
    for name in HOOK_NAMES:
        hook = _hook_path(repo, name)
        if _stat_path_if_present(hook) is None:
            return False
        content = hook.read_text(encoding="utf-8", errors="replace")
        if HOOK_BEGIN not in content or HOOK_END not in content:
            return False
    return True


def _is_excluded(repo: pathlib.Path, rel: str) -> bool:
    exclude = _git_path(repo, "info/exclude")
    if _stat_path_if_present(exclude) is None:
        return False
    return rel in exclude.read_text(encoding="utf-8", errors="replace").splitlines()


def _discover_adoption_status(
    repo: pathlib.Path,
    *,
    deadline: float | None = None,
) -> dict[str, Any]:
    if deadline is None:
        deadline = time.monotonic() + GIT_ADOPTION_VALIDATION_TIMEOUT_SECONDS
    try:
        adoption = _tracked_journal_adoption(repo, deadline=deadline)
    except (OSError, UserError) as exc:
        return {
            "adoption_status": "inconclusive",
            "adoption_error": {
                "code": getattr(exc, "code", "adoption_check_failed"),
                "message": str(exc),
            },
            "tracked_journal_adopted": None,
            "tracked_non_generated_journal_count": None,
            "valid_tracked_journal_count": None,
        }
    return {
        "adoption_status": (
            "adopted" if adoption["tracked_journal_adopted"] else "unadopted"
        ),
        "adoption_error": None,
        **adoption,
    }


def _discovery_error(exc: BaseException) -> dict[str, Any]:
    error: dict[str, Any] = {
        "code": getattr(exc, "code", "repo_discovery_failed"),
        "message": str(exc),
    }
    error_number = getattr(exc, "errno", None)
    if isinstance(error_number, int):
        error["errno"] = error_number
        error_name = errno.errorcode.get(error_number)
        if error_name is not None:
            error["error_name"] = error_name
    return error


def _enrich_discovered_repo(
    root: pathlib.Path,
    row: dict[str, Any],
    script: pathlib.Path,
    *,
    deadline: float | None = None,
) -> None:
    journal_root = root / JOURNAL_ROOT
    index_rel = DEFAULT_INDEX.as_posix()
    adoption = _discover_adoption_status(root, deadline=deadline)
    auxiliary_errors: dict[str, dict[str, Any]] = {}
    row.setdefault("coverage_status", "complete")

    try:
        journal_root_stat = _stat_path_if_present(journal_root)
        has_journal_dir = journal_root_stat is not None and stat.S_ISDIR(
            journal_root_stat.st_mode
        )
    except OSError as exc:
        has_journal_dir = None
        auxiliary_errors["has_journal_dir"] = _discovery_error(exc)

    try:
        journal_count = len(_journal_paths(root, deadline=deadline))
    except (OSError, UserError) as exc:
        journal_count = None
        auxiliary_errors["journal_count"] = _discovery_error(exc)

    try:
        index_ignored = _is_excluded(root, index_rel)
    except (OSError, UserError) as exc:
        index_ignored = None
        auxiliary_errors["index_ignored"] = _discovery_error(exc)

    try:
        hooks_installed = _has_hook_marker(root)
    except (OSError, UserError) as exc:
        hooks_installed = None
        auxiliary_errors["hooks_installed"] = _discovery_error(exc)

    try:
        index_stat = _stat_path_if_present(root / index_rel)
        has_index = index_stat is not None and stat.S_ISREG(index_stat.st_mode)
    except OSError as exc:
        has_index = None
        auxiliary_errors["has_index"] = _discovery_error(exc)

    discovery_status = (
        "inconclusive"
        if auxiliary_errors or adoption["adoption_status"] == "inconclusive"
        else "complete"
    )
    row.update(
        {
            "has_journal_dir": has_journal_dir,
            "journal_count": journal_count,
            "has_index": has_index,
            "index_ignored": index_ignored,
            "hooks_installed": hooks_installed,
            "discovery_status": discovery_status,
            "discovery_error": auxiliary_errors or None,
            "install_command": f"{shlex.quote(sys.executable)} {shlex.quote(str(script))} install-hooks --repo {shlex.quote(str(root))}",
            "generate_command": f"{shlex.quote(sys.executable)} {shlex.quote(str(script))} generate --repo {shlex.quote(str(root))} --output {index_rel} --ensure-exclude",
            **adoption,
        }
    )


def _repository_resolution_error_row(
    cwd: str,
    last_seen: str,
    error: dict[str, Any],
) -> dict[str, Any]:
    adoption_error = {
        "code": error["code"],
        "message": (
            "repository resolution failed before adoption could be checked: "
            f"{error['message']}"
        ),
    }
    return {
        "repo": None,
        "candidate_cwd": cwd,
        "last_seen": last_seen,
        "rollout_count": 0,
        "has_journal_dir": None,
        "journal_count": None,
        "has_index": None,
        "index_ignored": None,
        "hooks_installed": None,
        "coverage_status": "complete",
        "discovery_status": "inconclusive",
        "discovery_error": {"repo_resolution": error},
        "install_command": None,
        "generate_command": None,
        "adoption_status": "inconclusive",
        "adoption_error": adoption_error,
        "tracked_journal_adopted": None,
        "tracked_non_generated_journal_count": None,
        "valid_tracked_journal_count": None,
    }


def _discovery_coverage_error(
    exc: BaseException,
    state: _DiscoveryScanState,
    *,
    source: pathlib.Path,
) -> dict[str, Any]:
    error = _discovery_error(exc)
    error["source"] = str(source)
    if isinstance(exc, DiscoveryLimitExceeded):
        error.update(
            {
                "limit_name": exc.limit_name,
                "limit": exc.limit,
                "observed": exc.observed,
            }
        )
    error.update(state.coverage_counters())
    return error


def _mark_partial_discovery_coverage(
    rows: list[dict[str, Any]],
    errors: list[dict[str, Any]],
    error_count: int,
    state: _DiscoveryScanState,
) -> list[dict[str, Any]]:
    primary = dict(errors[0])
    primary["error_count"] = error_count
    primary["errors"] = errors
    primary.update(state.coverage_counters())
    if not rows:
        rows.append(
            {
                "repo": None,
                "candidate_cwd": None,
                "last_seen": None,
                "rollout_count": 0,
                "has_journal_dir": None,
                "journal_count": None,
                "has_index": None,
                "index_ignored": None,
                "hooks_installed": None,
                "coverage_status": "partial",
                "discovery_status": "inconclusive",
                "discovery_error": {"discovery_coverage": primary},
                "install_command": None,
                "generate_command": None,
                "adoption_status": "inconclusive",
                "adoption_error": {
                    "code": "discovery_coverage_incomplete",
                    "message": (
                        "repository adoption could not be checked because "
                        "session discovery coverage is partial"
                    ),
                },
                "tracked_journal_adopted": None,
                "tracked_non_generated_journal_count": None,
                "valid_tracked_journal_count": None,
            }
        )
        return rows

    for row in rows:
        row["coverage_status"] = "partial"
        row["discovery_status"] = "inconclusive"
        row_errors = dict(row.get("discovery_error") or {})
        row_errors["discovery_coverage"] = primary
        row["discovery_error"] = row_errors
    return rows


def _discover_repos(codex_home: pathlib.Path, since_days: int) -> list[dict[str, Any]]:
    state = _DiscoveryScanState(
        deadline=time.monotonic() + DISCOVERY_TIMEOUT_SECONDS,
    )
    cutoff = (dt.datetime.now(dt.timezone.utc) - dt.timedelta(days=since_days)).date()
    seen: dict[pathlib.Path, dict[str, Any]] = {}
    resolved_roots: dict[str, pathlib.Path | None] = {}
    resolution_errors: dict[str, dict[str, Any]] = {}
    unresolved: dict[str, dict[str, Any]] = {}
    resolution_deadlines: dict[str, float] = {}
    enrichment_remaining_budgets: dict[pathlib.Path, float] = {}
    enrichment_attempts: dict[pathlib.Path, int] = {}
    script = pathlib.Path(__file__).resolve()
    seen_rollouts: set[str] = set()
    coverage_errors: list[dict[str, Any]] = []
    coverage_error_count = 0
    stop_all_sources = False

    def record_coverage_error(
        exc: BaseException,
        source: pathlib.Path,
    ) -> None:
        nonlocal coverage_error_count, stop_all_sources
        coverage_error_count += 1
        error = _discovery_coverage_error(exc, state, source=source)
        if len(coverage_errors) < MAX_DISCOVERY_ERRORS:
            coverage_errors.append(error)
        if coverage_error_count > MAX_DISCOVERY_ERRORS:
            limit_error = _discovery_coverage_error(
                DiscoveryLimitExceeded(
                    "coverage error count",
                    MAX_DISCOVERY_ERRORS,
                    coverage_error_count,
                ),
                state,
                source=source,
            )
            if coverage_errors:
                coverage_errors[-1] = limit_error
            else:
                coverage_errors.append(limit_error)
            stop_all_sources = True

    for rollout_root in (
        codex_home / "sessions",
        codex_home / "archived_sessions",
    ):
        if stop_all_sources:
            break
        try:
            rollouts = _iter_rollout_paths(rollout_root, state)
            for rollout in rollouts:
                if stop_all_sources:
                    break
                try:
                    state.check_deadline()
                    if not _rollout_in_window(rollout, cutoff):
                        continue
                    rollout_identity = rollout.name
                    if rollout_identity in seen_rollouts:
                        continue
                    seen_rollouts.add(rollout_identity)
                    state.add_rollout()
                    last_seen = _rollout_last_seen(rollout)
                    roots_for_rollout: set[pathlib.Path] = set()
                    unresolved_for_rollout: set[str] = set()
                    cwds_for_rollout: set[str] = set()
                    try:
                        for raw_cwd in _extract_cwds(rollout, state):
                            state.check_deadline()
                            cwd = _normalize_discovery_cwd(raw_cwd)
                            state.add_cwd(cwd)
                            if cwd in cwds_for_rollout:
                                continue
                            cwds_for_rollout.add(cwd)
                            if cwd not in resolved_roots:
                                now = time.monotonic()
                                state.check_deadline()
                                resolution_deadline = min(
                                    state.deadline,
                                    now + GIT_ADOPTION_VALIDATION_TIMEOUT_SECONDS,
                                )
                                resolution_deadlines[cwd] = resolution_deadline
                                try:
                                    resolved_roots[cwd] = _repo_root_for_path(
                                        cwd,
                                        codex_home=codex_home,
                                        deadline=resolution_deadline,
                                    )
                                except (OSError, UserError) as exc:
                                    state.check_deadline()
                                    resolved_roots[cwd] = None
                                    resolution_errors[cwd] = _discovery_error(exc)
                            root = resolved_roots[cwd]
                            if root is None:
                                resolution_error = resolution_errors.get(cwd)
                                if resolution_error is not None:
                                    row = unresolved.setdefault(
                                        cwd,
                                        _repository_resolution_error_row(
                                            cwd,
                                            last_seen,
                                            resolution_error,
                                        ),
                                    )
                                    row["last_seen"] = max(
                                        str(row["last_seen"]),
                                        last_seen,
                                    )
                                    unresolved_for_rollout.add(cwd)
                                continue
                            if root not in seen:
                                row = {
                                    "repo": str(root),
                                    "last_seen": last_seen,
                                    "rollout_count": 0,
                                    "coverage_status": "complete",
                                }
                                seen[root] = row
                                remaining_budget = max(
                                    0.0,
                                    resolution_deadlines[cwd] - time.monotonic(),
                                )
                                enrichment_remaining_budgets[root] = remaining_budget
                                enrichment_attempts[root] = 1
                                _enrich_discovered_repo(
                                    root,
                                    row,
                                    script,
                                    deadline=resolution_deadlines[cwd],
                                )
                            else:
                                row = seen[root]
                                remaining_budget = max(
                                    0.0,
                                    resolution_deadlines[cwd] - time.monotonic(),
                                )
                                if (
                                    row.get("adoption_status") == "inconclusive"
                                    and enrichment_attempts[root]
                                    < DISCOVERY_ENRICHMENT_MAX_ATTEMPTS_PER_ROOT
                                    and remaining_budget
                                    >= (
                                        enrichment_remaining_budgets[root]
                                        + DISCOVERY_ENRICHMENT_RETRY_MIN_BUDGET_GAIN_SECONDS
                                    )
                                ):
                                    enrichment_remaining_budgets[root] = (
                                        remaining_budget
                                    )
                                    enrichment_attempts[root] += 1
                                    _enrich_discovered_repo(
                                        root,
                                        row,
                                        script,
                                        deadline=resolution_deadlines[cwd],
                                    )
                            roots_for_rollout.add(root)
                    finally:
                        for root in roots_for_rollout:
                            row = seen[root]
                            row["last_seen"] = max(
                                str(row["last_seen"]),
                                last_seen,
                            )
                            row["rollout_count"] = int(row["rollout_count"]) + 1
                        for cwd in unresolved_for_rollout:
                            row = unresolved[cwd]
                            row["rollout_count"] = int(row["rollout_count"]) + 1
                    state.check_deadline()
                except (DiscoveryDeadlineExceeded, DiscoveryLimitExceeded) as exc:
                    record_coverage_error(exc, rollout)
                    stop_all_sources = True
                except OSError as exc:
                    record_coverage_error(exc, rollout)
        except (DiscoveryDeadlineExceeded, DiscoveryLimitExceeded) as exc:
            record_coverage_error(exc, rollout_root)
            stop_all_sources = True
        except OSError as exc:
            record_coverage_error(exc, rollout_root)

    if not stop_all_sources:
        try:
            state.check_deadline()
        except DiscoveryDeadlineExceeded as exc:
            record_coverage_error(exc, codex_home)

    rows = [*seen.values(), *unresolved.values()]
    if coverage_errors:
        rows = _mark_partial_discovery_coverage(
            rows,
            coverage_errors,
            coverage_error_count,
            state,
        )
    return sorted(
        rows,
        key=lambda row: str(row["repo"] or row.get("candidate_cwd") or ""),
    )


def command_discover_repos(args: argparse.Namespace) -> int:
    codex_home = pathlib.Path(args.codex_home).expanduser().resolve()
    rows = _discover_repos(codex_home, args.since_days)
    if args.json_output:
        print(json.dumps(rows, ensure_ascii=False, indent=2, sort_keys=True))
        return 0
    for row in rows:
        repo_label = row["repo"] or row.get("candidate_cwd") or "<unresolved>"
        print(
            f"{repo_label}\tlast_seen={row['last_seen']}\t"
            f"journals={row['journal_count']}\thooks={row['hooks_installed']}\t"
            f"adoption={row['adoption_status']}\t"
            f"coverage={row.get('coverage_status', 'complete')}"
        )
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    generate = subparsers.add_parser(
        "generate", help="Generate a local project journal index."
    )
    generate.add_argument("--repo", required=True)
    generate.add_argument("--output", default=DEFAULT_INDEX.as_posix())
    generate.add_argument("--ensure-exclude", action="store_true")
    generate.set_defaults(func=command_generate)

    validate = subparsers.add_parser(
        "validate", help="Validate project journal frontmatter."
    )
    validate.add_argument("--repo", required=True)
    validate.set_defaults(func=command_validate)

    adoption = subparsers.add_parser(
        "adoption-status",
        help="Report valid tracked journal evidence for adoption checks.",
    )
    adoption.add_argument("--repo", required=True)
    adoption.set_defaults(func=command_adoption_status)

    hook_log = subparsers.add_parser(
        "_append-hook-log",
        help=argparse.SUPPRESS,
    )
    hook_log.add_argument("--repo", required=True)
    hook_log.set_defaults(func=command_append_hook_log)

    hooks = subparsers.add_parser(
        "install-hooks", help="Install local Git hooks for index refresh."
    )
    hooks.add_argument("--repo", required=True)
    hooks.set_defaults(func=command_install_hooks)

    discover = subparsers.add_parser(
        "discover-repos", help="Discover Codex-touched Git repos."
    )
    discover.add_argument(
        "--codex-home",
        default=os.environ.get("CODEX_HOME", "~/.codex"),
        help="Codex home to inspect. Defaults to CODEX_HOME or ~/.codex.",
    )
    discover.add_argument("--since-days", type=int, default=30)
    discover.add_argument("--json", action="store_true", dest="json_output")
    discover.set_defaults(func=command_discover_repos)

    return parser


def main(argv: list[str] | None = None) -> int:
    def dispatch() -> int:
        parser = build_parser()
        args = parser.parse_args(argv)
        _initialize_git_runtime()
        if isinstance(_GIT_RUNTIME_ERROR, UnsupportedPlatform):
            raise _GIT_RUNTIME_ERROR
        return int(args.func(args))

    try:
        return int(_run_with_deferred_termination(dispatch))
    except UserError as exc:
        print(f"error: {exc}", file=sys.stderr)
        for detail in getattr(exc, "__notes__", ())[
            :MAX_DEFERRED_SIGNAL_REPORT_DETAILS
        ]:
            print(
                f"note: {_bounded_signal_report_detail(detail)}",
                file=sys.stderr,
            )
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
